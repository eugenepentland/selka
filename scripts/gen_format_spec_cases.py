def zig_str(s):
    out = []
    for ch in s.encode('utf-8'):
        if ch == 0x22 or ch == 0x5c:
            out.append('\\' + chr(ch))
        elif 0x20 <= ch < 0x7f:
            out.append(chr(ch))
        else:
            out.append('\\x%02x' % ch)
    return '"' + ''.join(out) + '"'


