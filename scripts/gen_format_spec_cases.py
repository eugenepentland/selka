def round_away(x, n):
    """The language's rule: the exact binary value rounded half away from zero."""
    from decimal import Decimal, ROUND_HALF_UP
    if not math.isfinite(x) or n > 323:
        return x
    if n < -308:
        return math.copysign(0.0, x)
    import decimal
    with decimal.localcontext() as context:
        context.prec = 2000
        context.Emax = 5000
        context.Emin = -5000
        d = Decimal(x)
        q = Decimal(1).scaleb(-n)
        r = d.quantize(q, rounding=ROUND_HALF_UP)
        result = float(r)
    if result == 0.0:
        result = math.copysign(0.0, x)
    return result


