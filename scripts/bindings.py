#!/usr/bin/env python3
"""Generate standalone Python data bindings from a freshly checked module schema."""
import argparse
from collections import deque
import hashlib
import json
import math
import os
from pathlib import Path
import subprocess
import shutil
import sys
import tempfile
import time

ROOT = Path(__file__).resolve().parents[1]
RUNTIME = Path(__file__).with_name('python_bindings_runtime.py')
MAX_BYTES = 16 * 1024 * 1024
ORDINARY = {'integer', 'boolean', 'record', 'array', 'table', 'enumeration', 'tagged_union', 'result'}


def unique(pairs):
    output = {}
    for key, value in pairs:
        if key in output:
            raise ValueError('duplicate schema key: ' + key)
        output[key] = value
    return output


def canonical(value):
    return json.dumps(value, ensure_ascii=False, allow_nan=False, separators=(',', ':'))


def identifier(name):
    # Escape the escape character too: language names cannot collide after mapping.
    return ''.join(chr(byte) if (65 <= byte <= 90 or 97 <= byte <= 122 or 48 <= byte <= 57) else f'_x{byte:02x}' for byte in name.encode('utf-8'))


def class_name(name):
    return 'T_' + identifier(name)


def dependencies(definition):
    kind = definition['kind']
    if kind in ('array', 'table'):
        return [definition['element']] + ([definition['key']] if kind == 'table' else [])
    if kind == 'record':
        return [field['type'] for field in definition['fields']]
    if kind in ('enumeration', 'tagged_union', 'result'):
        return [case['payload'] for case in definition['cases'] if 'payload' in case]
    return []


def analyze(schema):
    if schema.get('version') != 'language-schema-v1' or schema.get('representation') != 'language-contracts-no-wire-format-or-abi':
        raise ValueError('unsupported schema contract')
    definitions = {}
    for definition in schema['types']:
        name = definition['name']
        if name in definitions:
            raise ValueError('duplicate schema type: ' + name)
        definitions[name] = definition
        for key in ('fields', 'cases'):
            names = [item['name'] for item in definition.get(key, [])]
            if len(names) != len(set(names)):
                raise ValueError('duplicate schema ' + key + ': ' + name)
    reverse = {name: [] for name in definitions}
    unsupported = set()
    for name, definition in definitions.items():
        if definition['kind'] not in ORDINARY or definition.get('opaque') or definition.get('move_only'):
            unsupported.add(name)
        for dependency in dependencies(definition):
            if dependency not in reverse:
                raise ValueError('unresolved schema type: ' + dependency)
            reverse[dependency].append(name)
    pending = deque(sorted(unsupported))
    while pending:
        for parent in reverse[pending.popleft()]:
            if parent not in unsupported:
                unsupported.add(parent)
                pending.append(parent)
    return definitions, unsupported


def generator_snapshot():
    runtime = RUNTIME.read_text(encoding='utf-8')
    identity = hashlib.sha256(Path(__file__).read_bytes() + b'\0' + runtime.encode()).hexdigest()
    return runtime, identity


def generate(schema, max_bytes=MAX_BYTES, *, snapshot=None):
    definitions, unsupported = analyze(schema)
    runtime, generator_hash = snapshot if snapshot is not None else generator_snapshot()
    schema_text = canonical(schema)
    schema_hash = hashlib.sha256(schema_text.encode()).hexdigest()
    lines = [
        '# Generated by mylang Python bindings v1. Regenerate from checked source.',
        'from __future__ import annotations',
        'from dataclasses import dataclass',
        'from enum import Enum',
        'from collections.abc import Mapping',
        'from types import MappingProxyType',
        'import json',
        'import re',
        '',
        "BINDINGS_VERSION = 'python-bindings-v1'",
        f'SCHEMA_SHA256 = {schema_hash!r}',
        f'GENERATOR_SHA256 = {generator_hash!r}',
        f'_SCHEMA = json.loads({schema_text!r})',
        "_DEFINITIONS = {item['name']: item for item in _SCHEMA['types']}",
        f'UNSUPPORTED_TYPES = frozenset({sorted(unsupported)!r})',
        "TYPE_NAMES = tuple(sorted(set(_DEFINITIONS) - UNSUPPORTED_TYPES))",
        '',
    ]

    def annotation(name):
        kind = definitions[name]['kind']
        if kind == 'integer':
            return 'int'
        if kind == 'boolean':
            return 'bool'
        if kind == 'array':
            return 'tuple[' + annotation(definitions[name]['element']) + ', ...]'
        if kind == 'table':
            return 'Mapping[' + annotation(definitions[name]['key']) + ', ' + annotation(definitions[name]['element']) + ']'
        return class_name(name)

    types = {}
    cases = {}
    fields = {}
    for name in sorted(definitions):
        if name in unsupported:
            continue
        definition = definitions[name]
        kind = definition['kind']
        cls = class_name(name)
        if kind in ('record', 'enumeration', 'tagged_union', 'result'):
            types[name] = cls
        if kind == 'record':
            lines += ['@dataclass(frozen=True, slots=True)', f'class {cls}:']
            fields[name] = {}
            for field in definition['fields']:
                attribute = 'f_' + identifier(field['name'])
                fields[name][field['name']] = attribute
                lines.append(f'    {attribute}: {annotation(field["type"])}')
            if not definition['fields']:
                lines.append('    pass')
        elif kind == 'enumeration':
            lines.append(f'class {cls}(Enum):')
            for case in definition['cases']:
                lines.append(f'    v_{identifier(case["name"])} = {case["name"]!r}')
            if not definition['cases']:
                lines.append('    pass')
        elif kind in ('tagged_union', 'result'):
            lines += [f'class {cls}:', '    __slots__ = ()']
            cases[name] = {}
            for case in definition['cases']:
                variant = cls + '_C_' + identifier(case['name'])
                cases[name][case['name']] = variant
                lines += ['', '@dataclass(frozen=True, slots=True)', f'class {variant}({cls}):']
                lines.append('    value: ' + annotation(case['payload']) if 'payload' in case else '    pass')
        lines.append('')
    lines += [
        'TYPES = MappingProxyType({' + ', '.join(f'{name!r}: {cls}' for name, cls in types.items()) + '})',
        'CASES = MappingProxyType({' + ', '.join(f'{name!r}: MappingProxyType({{' + ', '.join(f'{key!r}: {cls}' for key, cls in members.items()) + '})' for name, members in cases.items()) + '})',
        f'FIELDS = MappingProxyType({{name: MappingProxyType(fields) for name, fields in {fields!r}.items()}})',
        '_CASE_NAMES = {cls: (name, case) for name, members in CASES.items() for case, cls in members.items()}',
        '_TYPE_NAMES = {cls: name for name, cls in TYPES.items()}',
        '_TYPE_NAMES.update({cls: name for cls, (name, _) in _CASE_NAMES.items()})',
        "_CASES = {name: {case['name']: case for case in definition['cases']} for name, definition in _DEFINITIONS.items() if definition['kind'] in ('tagged_union', 'result')}",
        '', runtime,
    ]
    output = '\n'.join(lines).encode('utf-8')
    if len(output) > max_bytes:
        raise ValueError('generated bindings exceed output byte limit')
    compile(output, '<generated-bindings>', 'exec')
    return output, {'version': 'python-bindings-v1', 'schema_sha256': schema_hash, 'generator_sha256': generator_hash,
                    'sha256': hashlib.sha256(output).hexdigest(), 'bytes': len(output), 'supported_types': len(definitions) - len(unsupported),
                    'unsupported_types': sorted(unsupported)}


def checked_schema(compiler, entry, timeout, max_bytes=MAX_BYTES):
    with tempfile.TemporaryFile() as output, tempfile.TemporaryFile() as errors:
        process = subprocess.Popen([str(compiler), 'schema-project', str(entry), '--schema-report'], stdout=output, stderr=errors)
        deadline = time.monotonic() + timeout
        try:
            while True:
                status = process.poll()
                if os.fstat(output.fileno()).st_size + os.fstat(errors.fileno()).st_size > max_bytes:
                    raise ValueError('compiler schema output exceeds capture byte limit')
                if status is not None:
                    break
                if time.monotonic() >= deadline:
                    raise ValueError('compiler schema generation timed out')
                time.sleep(0.02)
        finally:
            if process.poll() is None:
                process.terminate()
                try:
                    process.wait(timeout=2)
                except subprocess.TimeoutExpired:
                    process.kill()
                    process.wait()
        errors.seek(0)
        diagnostics = errors.read(max_bytes + 1)
        if diagnostics:
            sys.stderr.buffer.write(diagnostics)
        if status != 0:
            raise CompilerFailure(status)
        output.seek(0)
        schema = json.loads(output.read(max_bytes + 1), object_pairs_hook=unique)
        if not isinstance(schema, dict):
            raise ValueError('invalid compiler schema document')
        return validate_schema_report(schema)


def validate_schema_report(document):
    if not isinstance(document, dict) or set(document) != {'version', 'source_sha256', 'source', 'schema_sha256', 'schema'} or document['version'] != 'schema-report-v1':
        raise ValueError('invalid schema receipt')
    source, schema = document['source'], document['schema']
    if not isinstance(source, dict) or not isinstance(schema, dict) or source.get('version') != 'schema-source-v1' or schema.get('version') != 'language-schema-v1':
        raise ValueError('unsupported schema receipt payload')
    if digest(source) != document['source_sha256'] or digest(schema) != document['schema_sha256']:
        raise ValueError('schema receipt checksum mismatch')
    if set(source) != {'version', 'entry', 'implementation', 'sources'} or source['entry'] != schema.get('entry'):
        raise ValueError('schema receipt entry mismatch')
    implementation = source['implementation']
    if not isinstance(implementation, dict) or set(implementation) != {'compiler_sha256', 'zig_version', 'architecture', 'os', 'abi', 'optimize'} or any(type(value) is not str for value in implementation.values()):
        raise ValueError('invalid schema compiler identity')
    def hash_text(value):
        return type(value) is str and len(value) == 64 and all(char in '0123456789abcdef' for char in value)
    if not hash_text(implementation['compiler_sha256']) or type(source['sources']) is not list or not source['sources']:
        raise ValueError('invalid schema source identities')
    names = set()
    for item in source['sources']:
        if not isinstance(item, dict) or set(item) != {'module', 'path', 'sha256', 'bytes', 'imports'}:
            raise ValueError('invalid schema source record')
        if type(item['module']) is not str or not item['module'] or item['module'] in names or type(item['path']) is not str or type(item['bytes']) is not int or item['bytes'] < 0 or not hash_text(item['sha256']) or type(item['imports']) is not list:
            raise ValueError('invalid schema source metadata')
        for imported in item['imports']:
            if not isinstance(imported, dict) or set(imported) != {'module', 'alias'} or type(imported['module']) is not str or imported['module'] not in names or type(imported['alias']) is not str:
                raise ValueError('invalid schema dependency order')
        names.add(item['module'])
    if source['sources'][-1]['module'] != source['entry']:
        raise ValueError('schema entry is not the final dependency root')
    return document


class CompilerFailure(Exception):
    def __init__(self, status):
        self.status = status


def store(path, data):
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(prefix='.bindings-', suffix='.tmp', dir=path.parent, delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def digest(value):
    return hashlib.sha256(canonical(value).encode()).hexdigest()


def file_digest(path):
    identity = hashlib.sha256()
    with path.open('rb') as stream:
        while chunk := stream.read(1024 * 1024):
            identity.update(chunk)
    return identity.hexdigest()


def matches(path, data):
    try:
        with path.open('rb') as stream:
            return stream.read(len(data) + 1) == data
    except FileNotFoundError:
        return False


def load_cached(path, request):
    limit = 12 * request['max_output_bytes'] + 65536
    try:
        with path.open('rb') as stream:
            data = stream.read(limit + 1)
    except FileNotFoundError:
        return None, 'not-found'
    try:
        if len(data) > limit:
            raise ValueError('cache envelope exceeds byte limit')
        document = json.loads(data, object_pairs_hook=unique)
        if set(document) != {'version', 'payload', 'sha256'} or document['version'] != 'python-bindings-cache-v1':
            raise ValueError('invalid cache envelope')
        payload = document['payload']
        if set(payload) != {'request', 'source', 'report'} or digest(payload) != document['sha256']:
            raise ValueError('invalid cache checksum')
        if canonical(payload['request']) != canonical(request):
            raise ValueError('cache request mismatch')
        source = payload['source'].encode('utf-8')
        report = payload['report']
        report_fields = {'version', 'schema_sha256', 'generator_sha256', 'sha256', 'bytes', 'supported_types', 'unsupported_types'}
        wrapper_fields = {'callable_functions', 'unsupported_functions'}
        if set(report) not in (report_fields, report_fields | wrapper_fields):
            raise ValueError('invalid cached report')
        if report['version'] != 'python-bindings-v1' or report['schema_sha256'] != request['schema_sha256'] or report['generator_sha256'] != request['generator_sha256']:
            raise ValueError('cached identity mismatch')
        if type(report['bytes']) is not int or report['bytes'] != len(source) or len(source) > request['max_output_bytes'] or hashlib.sha256(source).hexdigest() != report['sha256']:
            raise ValueError('cached source mismatch')
        if type(report['supported_types']) is not int or report['supported_types'] < 0:
            raise ValueError('invalid cached count')
        unsupported = report['unsupported_types']
        if type(unsupported) is not list or any(type(name) is not str for name in unsupported) or unsupported != sorted(set(unsupported)):
            raise ValueError('invalid cached unsupported types')
        if wrapper_fields <= report.keys():
            if type(report['callable_functions']) is not int or report['callable_functions'] < 0:
                raise ValueError('invalid cached callable count')
            functions = report['unsupported_functions']
            if type(functions) is not dict or any(type(name) is not str or not name or type(reason) is not str or not reason for name, reason in functions.items()):
                raise ValueError('invalid cached unsupported functions')
        compile(source, '<cached-bindings>', 'exec')
        return (source, report), 'matching-request'
    except (ValueError, KeyError, TypeError, AttributeError, SyntaxError, RecursionError):
        return None, 'invalid-cache'


def build(compiler, entry, output_path, *, cache_dir=None, timeout=90, max_schema_bytes=MAX_BYTES, max_output_bytes=MAX_BYTES):
    if type(timeout) not in (int, float) or not math.isfinite(timeout) or timeout <= 0 or any(type(limit) is not int or limit <= 0 for limit in (max_schema_bytes, max_output_bytes)):
        raise ValueError('generation limits must be finite and positive')
    resolved = shutil.which(str(compiler))
    if resolved is None:
        raise FileNotFoundError('compiler executable not found: ' + str(compiler))
    executable = Path(resolved).resolve()
    compiler_hash = file_digest(executable)
    schema_receipt = checked_schema(executable, entry, timeout, max_schema_bytes)
    schema = schema_receipt['schema']
    if file_digest(executable) != compiler_hash:
        raise ValueError('compiler changed during schema checking; retry generation')
    snapshot = generator_snapshot()
    request = {
        'version': 'python-bindings-request-v1',
        'schema_sha256': digest(schema),
        'generator_sha256': snapshot[1],
        'compiler_sha256': compiler_hash,
        'schema_compiler_sha256': schema_receipt['source']['implementation']['compiler_sha256'],
        'python': {'implementation': sys.implementation.name, 'version': sys.version,
                   'cache_tag': sys.implementation.cache_tag, 'optimize': sys.flags.optimize},
        'max_output_bytes': max_output_bytes,
    }
    request_hash = digest(request)
    cached = None
    reason = 'cache-disabled'
    cache_path = cache_dir / (request_hash + '.json') if cache_dir is not None else None
    if cache_path is not None:
        if output_path.resolve() == cache_path.resolve():
            raise ValueError('output cannot replace its cache entry')
        cached, reason = load_cached(cache_path, request)
    if cached is None:
        source, report = generate(schema, max_output_bytes, snapshot=snapshot)
        if cache_path is not None:
            payload = {'request': request, 'source': source.decode('utf-8'), 'report': report}
            cache_path.parent.mkdir(parents=True, exist_ok=True)
            store(cache_path, canonical({'version': 'python-bindings-cache-v1', 'payload': payload, 'sha256': digest(payload)}).encode())
    else:
        source, report = cached
    unchanged = matches(output_path, source)
    if not unchanged:
        store(output_path, source)
    return dict(report, version='python-bindings-run-v1', output=str(output_path), request=request, request_sha256=request_hash,
                schema_source=schema_receipt['source'], schema_source_sha256=schema_receipt['source_sha256'],
                frontend='checked', cache=('disabled' if cache_path is None else 'hit' if cached is not None else 'miss'),
                reason=reason, generation=('skipped' if cached is not None else 'executed'),
                installation=('unchanged' if unchanged else 'replaced'))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('entry', type=Path)
    parser.add_argument('--compiler', type=Path, default=ROOT / 'zig-out/bin/mylang')
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--cache-dir', type=Path)
    parser.add_argument('--timeout', type=float, default=90)
    parser.add_argument('--max-schema-bytes', type=int, default=MAX_BYTES)
    parser.add_argument('--max-output-bytes', type=int, default=MAX_BYTES)
    args = parser.parse_args()
    if not math.isfinite(args.timeout) or args.timeout <= 0 or args.max_schema_bytes <= 0 or args.max_output_bytes <= 0:
        parser.error('generation limits must be finite and positive')
    if args.output.resolve() in {args.entry.resolve(), args.compiler.resolve(), Path(__file__).resolve(), RUNTIME.resolve()}:
        parser.error('output cannot replace the entry, compiler, or generator')
    try:
        report = build(args.compiler, args.entry, args.output, cache_dir=args.cache_dir, timeout=args.timeout,
                       max_schema_bytes=args.max_schema_bytes, max_output_bytes=args.max_output_bytes)
        print(canonical(report))
    except CompilerFailure as error:
        return 1 if error.status == 1 else 2
    except (OSError, ValueError, KeyError, TypeError, RecursionError) as error:
        print(f'bindings: {error}', file=sys.stderr)
        return 2
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
