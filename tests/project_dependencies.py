#!/usr/bin/env python3
"""Independent hashes and compiler-resolved import receipts for verification consumers."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import tempfile


def compiler_identity(compiler):
    """The compiler's embedded build-time identity, reported rather than hashed from the binary."""
    report = subprocess.run([str(compiler), '--features'], capture_output=True, text=True, timeout=60)
    assert report.returncode == 0, report.stderr
    identity = json.loads(report.stdout)['compiler_sha256']
    assert isinstance(identity, str) and len(identity) == 64
    return identity


def digest(data):
    return hashlib.sha256(data).hexdigest()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--compiler', type=Path, required=True)
    compiler = parser.parse_args().compiler.resolve()
    with tempfile.TemporaryDirectory(prefix='dependency graph ') as temporary:
        root = Path(temporary)
        (root / 'main.my').write_text('module main\nimport leaf as renamed\nimport config.values as v\n\ndef main() -> i64:\n    return renamed.value() + v.count()\n')
        leaf = root / 'leaf.my'
        leaf.write_text('module leaf\n\n\npublic def value() -> i64:\n    return 4\n')
        manifest = root / 'inputs.json'
        manifest.write_text(json.dumps({'version': 1, 'module': 'config.values', 'values': [{'name': 'count', 'type': 'i64', 'value': '7'}]}))

        def invoke(directory=root):
            return subprocess.run([str(compiler), 'project-dependencies', str(directory / 'main.my'), '--inputs=' + str(directory / 'inputs.json')], capture_output=True, timeout=90)

        def report():
            result = invoke()
            assert result.returncode == 0, result.stderr
            return json.loads(result.stdout)

        first = report()
        assert first['version'] == 'project-dependencies-v1' and first['complete']
        assert first['implementation']['compiler_sha256'] == compiler_identity(compiler)
        sources = {s['module']: s for s in first['inputs']}
        assert set(sources) == {'main', 'leaf', 'config.values'}
        assert sources['main']['imports'] == [{'module': 'leaf', 'alias': 'renamed'}, {'module': 'config.values', 'alias': 'v'}]
        for name in ('main', 'leaf'):
            raw = (root / sources[name]['path']).read_bytes()
            assert sources[name]['sha256'] == digest(raw) and sources[name]['bytes'] == len(raw)
        generated = subprocess.run([str(compiler), 'input-module', str(manifest)], capture_output=True, check=True, timeout=90).stdout
        assert sources['config.values']['sha256'] == digest(generated)
        assert first['manifests'] == [{'module': 'config.values', 'path': str(manifest), 'sha256': digest(manifest.read_bytes())}]
        assert report() == first
        copied = root / 'another worktree'
        shutil.copytree(root, copied, ignore=shutil.ignore_patterns('another worktree'))
        relocated = json.loads(invoke(copied).stdout)
        assert relocated['inputs'] == first['inputs']
        assert relocated['implementation'] == first['implementation']
        manifest.write_text(manifest.read_text() + '\n')
        assert report()['manifests'][0]['sha256'] != first['manifests'][0]['sha256']
        leaf.write_text(leaf.read_text().replace('return 4', 'return 5'))
        assert next(s for s in report()['inputs'] if s['module'] == 'leaf')['sha256'] != sources['leaf']['sha256']
        for text in ('module leaf\n\n\npublic def value() -> i64:\n    return True\n', 'module leaf\nimport missing\n'):
            leaf.write_text(text)
            result = invoke()
            assert result.returncode != 0 and not result.stdout and b'E_' in result.stderr, result
        leaf.unlink()
        assert invoke().returncode != 0
    embedded_receipts(compiler)
    print('Project dependencies: checked imports, raw source/manifest/tool hashes, generated bytes, relocation, embedded files and failed-source suppression pass')


def embedded_receipts(compiler):
    """A module that embeds a file lists it with the file's digest, so its edit is an input change."""
    with tempfile.TemporaryDirectory(prefix='embedded inputs ') as temporary:
        root = Path(temporary)
        (root / 'assets').mkdir()
        (root / 'main.my').write_text('module main\nimport data\n\n\ndef main() -> int:\n    return len(data.TABLE)\n')
        (root / 'data.my').write_text('module data\n\npublic const TABLE: bytes = embed_bytes("assets/table.bin")\n')
        table = root / 'assets' / 'table.bin'
        table.write_bytes(b'\x00\x01table')

        def report():
            result = subprocess.run([str(compiler), 'project-dependencies', str(root / 'main.my')], capture_output=True, timeout=90)
            assert result.returncode == 0, result.stderr
            return json.loads(result.stdout)

        first = report()
        listed = first['embeds']
        assert len(listed) == 1 and listed[0]['module'] == 'data' and listed[0]['path'] == 'assets/table.bin', listed
        assert listed[0]['status'] == 'ok' and listed[0]['bytes'] == 7 and len(listed[0]['blake3']) == 64
        assert report() == first
        table.write_bytes(b'\x00\x01tablet')
        second = report()
        assert second['embeds'][0]['blake3'] != listed[0]['blake3'] and second['embeds'][0]['bytes'] == 8
        assert second['inputs'] == first['inputs']
        table.write_bytes(b'\x00\x01table')
        assert report() == first
        table.unlink()
        missing = subprocess.run([str(compiler), 'project-dependencies', str(root / 'main.my')], capture_output=True, timeout=90)
        assert missing.returncode != 0 and b'E_EMBED_MISSING' in missing.stderr, missing


if __name__ == '__main__':
    main()
