#!/usr/bin/env python3
"""Generate the Selka lexer's token-kind and keyword tables from the Zig lexer.

    python3 selfhost/tools/gen_lexer_tables.py [--compiler PATH] [--check]

`selka dump-tokens --tables` lists every `Tag` of `src/lexer.zig` in declaration
order and every reserved spelling with the tag it lexes as. This script turns that
text into two Selka modules under `selfhost/frontend/`:

* `token_kinds.selka`: `enum Kind` with one case per tag, and `kind_name`, the tag's
  spelling (the `kind` field of `tokens-v1`).
* `keywords.selka`: `keyword_kind(src, start, length)`, a decision tree over the
  reserved spellings, so classifying a name reads at most a few bytes and slices
  nothing.

`--check` writes nothing and exits 1 when a committed file differs from what the
compiler's tables generate; the syntax parity test runs it, so a keyword or tag
added to the Zig lexer cannot leave the Selka lexer behind.
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FRONTEND = ROOT / "selfhost" / "frontend"
BANNER = "# Generated by selfhost/tools/gen_lexer_tables.py from `selka dump-tokens --tables`. Do not edit.\n"


def read_tables(compiler: Path) -> tuple[list[str], list[tuple[str, str]]]:
    """The tag names in declaration order and the (word, tag) pairs in table order."""
    done = subprocess.run([str(compiler), "dump-tokens", "--tables"], capture_output=True, text=True, check=True)
    lines = done.stdout.splitlines()
    if lines[0] != "tokens-tables-v1":
        raise SystemExit(f"{compiler}: unexpected tables header {lines[0]!r}")
    count = int(lines[1].split()[1])
    kinds = lines[2:2 + count]
    header = lines[2 + count].split()
    pairs = [tuple(line.split()[1:3]) for line in lines[3 + count:]]  # type: ignore[misc]
    if header[0] != "keywords" or int(header[1]) != len(pairs):
        raise SystemExit(f"{compiler}: keyword count {header[1:]} does not match {len(pairs)} lines")
    return kinds, pairs  # type: ignore[return-value]


def kinds_module(kinds: list[str]) -> str:
    out = [BANNER, "# The lexer's token categories, in the Zig declaration order.\n", "public enum Kind:\n"]
    out += [f"    {name}\n" for name in kinds]
    out.append("\n\n# The tag's spelling, as `selka dump-tokens` writes it.\npublic func kind_name(kind: Kind) -> str:\n    match kind:\n")
    for name in kinds:
        out.append(f"        case {name}:\n            return \"{name}\"\n")
    return "".join(out)


class Node:
    def __init__(self) -> None:
        self.children: dict[int, "Node"] = {}
        self.tag: str | None = None


def build_trie(pairs: list[tuple[str, str]]) -> Node:
    root = Node()
    for word, tag in pairs:
        node = root
        for byte in word.encode():
            node = node.children.setdefault(byte, Node())
        if node.tag is not None:
            raise SystemExit(f"duplicate reserved spelling {word}")
        node.tag = tag
    return root


def emit(node: Node, depth: int, indent: int, out: list[str]) -> None:
    pad = "    " * indent
    if node.tag is not None:
        out.append(f"{pad}if length == {depth}:\n{pad}    return token_kinds.Kind.{node.tag}\n")
    if not node.children:
        return
    out.append(f"{pad}if length > {depth}:\n")
    out.append(f"{pad}    const c{depth} = src[start + {depth}]\n")
    for byte in sorted(node.children):
        shown = chr(byte)
        out.append(f"{pad}    if c{depth} == {byte}: # {shown}\n")
        emit(node.children[byte], depth + 1, indent + 2, out)


def keywords_module(pairs: list[tuple[str, str]]) -> str:
    out = [
        BANNER,
        "# The tag a name lexes as: a reserved spelling's keyword (or operator word) tag, else `ident`.\n",
        "# `src[start:start + length]` is the name; the function reads bytes and builds nothing.\n",
        "import token_kinds\n\n",
        "public func keyword_kind(src: bytes, start: int, length: int) -> token_kinds.Kind:\n",
    ]
    emit(build_trie(pairs), 0, 1, out)
    out.append("    return token_kinds.Kind.ident\n")
    return "".join(out)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--compiler", type=Path, default=ROOT / "zig-out" / "bin" / "selka")
    parser.add_argument("--check", action="store_true", help="compare with the committed files instead of writing")
    parser.add_argument("--out", type=Path, default=FRONTEND)
    args = parser.parse_args(argv)
    kinds, pairs = read_tables(args.compiler)
    files = {"token_kinds.selka": kinds_module(kinds), "keywords.selka": keywords_module(pairs)}
    stale = [name for name, text in files.items() if not (args.out / name).is_file() or (args.out / name).read_text() != text]
    if args.check:
        for name in stale:
            print(f"gen_lexer_tables: {name} differs from the compiler's tables; run python3 selfhost/tools/gen_lexer_tables.py", file=sys.stderr)
        return 1 if stale else 0
    args.out.mkdir(parents=True, exist_ok=True)
    for name in stale:
        (args.out / name).write_text(files[name])
        print(f"wrote {args.out / name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
