//! Generated interface files: one canonical, body-free text per project module,
//! checked in beside its source (`pkg/billing.my` beside `pkg/billing.api`).
//!
//! The text is built from the declaration index alone (`interfaces.Index`), with
//! the same canonical type descriptors, requirement tokens, contract clauses and
//! derived effect ceilings `list-interfaces` publishes, laid out in mylang
//! declaration syntax. Nothing is read from a function body or a private
//! declaration, so an edit that changes only those never changes the file.
//! This module renders and compares text; `mylang api` does the file I/O.
const std = @import("std");
const ast = @import("ast.zig");
const interfaces = @import("interfaces.zig");
const source = @import("source.zig");
const typed = @import("typed.zig");

/// First line of every generated file. `mylang api --write` deletes a stale
/// `.api` file only when it still carries this line.
pub const header = "# generated by mylang api; do not edit";
/// Extension that replaces a module source's `.my`.
pub const extension = ".api";
/// Declaration name the comparison gives the module docstring's paragraph.
pub const docstring_name = "__doc__";
/// Source-path prefix of a compiler-embedded standard module, which has no
/// interface file of its own.
const standard_prefix = "@stdlib/";
/// Indentation of a member, field or case line inside a declaration block.
const indent = "    ";

/// Failures while rendering one module's interface text.
pub const Error = interfaces.ContractError;

/// Whether a loaded module is a project source that gets an interface file:
/// every module except the compiler-embedded standard library.
pub fn projectModule(src: source.Source) bool {
    return !std.mem.startsWith(u8, src.path, standard_prefix);
}

/// The interface file path for a module source path: `pkg/billing.my` becomes
/// `pkg/billing.api`. The caller owns the returned slice.
pub fn apiPath(allocator: std.mem.Allocator, source_path: []const u8) std.mem.Allocator.Error![]u8 {
    const stem = if (std.mem.endsWith(u8, source_path, ".my")) source_path[0 .. source_path.len - 3] else source_path;
    return std.mem.concat(allocator, u8, &.{ stem, extension });
}

/// Whether `bytes` is a file `mylang api` generated: its first line is `header`.
pub fn generated(bytes: []const u8) bool {
    if (!std.mem.startsWith(u8, bytes, header)) return false;
    return bytes.len == header.len or bytes[header.len] == '\n';
}

/// The module name a generated file declares on its `module` line, or null.
pub fn declaredModule(bytes: []const u8) ?[]const u8 {
    var lines = std.mem.splitScalar(u8, bytes, '\n');
    while (lines.next()) |line| {
        if (std.mem.startsWith(u8, line, "module ")) return std.mem.trim(u8, line["module ".len..], " \t\r");
    }
    return null;
}

/// Render one module's interface file. The text is the header, the `module`
/// metadata line, the first paragraph of the module docstring, then every public
/// declaration in source order as a blank-line separated block. The caller
/// owns the returned bytes; intermediate text lives in the project arena.
/// The `.api` module line is artifact metadata, not a `.my` source header; its
/// identity is always the project loader's path-derived module name.
pub fn render(allocator: std.mem.Allocator, index: *interfaces.Index, module: usize) Error![]u8 {
    var renderer: Renderer = .{ .index = index, .module = module, .arena = index.project.arena.allocator() };
    try renderer.line(header);
    try renderer.print("module {s}\n", .{index.project.modules.items[module].name});
    try renderer.docstring();
    const symbols = index.units[module].symbols.items;
    const order = try renderer.arena.alloc(usize, symbols.len);
    for (order, 0..) |*slot, position| slot.* = position;
    std.mem.sort(usize, order, &renderer, Renderer.sourceOrder);
    for (order) |position| {
        const symbol = symbols[position];
        if (!symbol.exported or symbol.owner != null) continue;
        try renderer.text("\n");
        try renderer.declaration(symbol);
    }
    return allocator.dupe(u8, renderer.out.items) catch error.OutOfMemory;
}

/// Accumulates one module's interface text in the project arena.
const Renderer = struct {
    index: *interfaces.Index,
    module: usize,
    arena: std.mem.Allocator,
    out: std.ArrayList(u8) = .empty,

    fn text(self: *Renderer, bytes: []const u8) Error!void {
        try self.out.appendSlice(self.arena, bytes);
    }
    fn line(self: *Renderer, bytes: []const u8) Error!void {
        try self.text(bytes);
        try self.text("\n");
    }
    fn print(self: *Renderer, comptime format: []const u8, arguments: anytype) Error!void {
        try self.text(try std.fmt.allocPrint(self.arena, format, arguments));
    }
    fn src(self: *const Renderer) source.Source {
        return self.index.project.modules.items[self.module].src;
    }
    fn syntax(self: *const Renderer) ast.Program {
        return self.index.units[self.module].syntax;
    }

    /// Order symbols by where their declaration (or re-export directive) begins.
    fn sourceOrder(self: *Renderer, a: usize, b: usize) bool {
        const symbols = self.index.units[self.module].symbols.items;
        return ast.declarationStart(self.syntax(), symbols[a].span) < ast.declarationStart(self.syntax(), symbols[b].span);
    }

    /// The module docstring's first paragraph, one trimmed line per source line.
    fn docstring(self: *Renderer) Error!void {
        const doc = ast.docstringOf(self.syntax(), ast.module_docstring_span) orelse return;
        const trimmed = std.mem.trim(u8, doc.text, " \t\r\n");
        if (trimmed.len == 0) return;
        const end = std.mem.indexOf(u8, trimmed, "\n\n") orelse trimmed.len;
        var lines = std.mem.splitScalar(u8, trimmed[0..end], '\n');
        var first = true;
        try self.text("\"\"\"");
        while (lines.next()) |raw| {
            const piece = std.mem.trim(u8, raw, " \t\r");
            if (piece.len == 0) break;
            if (!first) try self.text("\n");
            first = false;
            try self.text(piece);
        }
        try self.line("\"\"\"");
    }

    fn declaration(self: *Renderer, symbol: interfaces.Symbol) Error!void {
        if (symbol.re_export) |target| {
            const target_symbol = self.index.units[target.module].symbols.items[target.symbol];
            return self.print("export {s}.{s}\n", .{ self.index.project.modules.items[target.module].name, target_symbol.name });
        }
        try self.attributes(symbol.span, "");
        switch (symbol.kind) {
            .function => try self.functionLine(symbol.span, "public "),
            .type => try self.typeDeclaration(symbol),
            .constraint => try self.constraintBlock(symbol.span),
        }
    }

    /// `@deprecated` and contract clauses above one declaration, in source order,
    /// each with its whitespace folded to single spaces.
    fn attributes(self: *Renderer, name: source.Span, prefix: []const u8) Error!void {
        for (ast.attributesOf(self.syntax(), name)) |attribute| {
            if (attribute.kind != .deprecated and !attribute.kind.contract()) continue;
            try self.text(prefix);
            try interfaces.appendFolded(&self.out, self.arena, self.src().text(attribute.span));
            try self.text("\n");
        }
    }

    fn functionLine(self: *Renderer, name: source.Span, prefix: []const u8) Error!void {
        const declared = self.index.findFunction(self.index.units[self.module], name) orelse return error.InternalError;
        const signature = declared.signature;
        if (declared.policy.constant) return self.constantLine(declared);
        try self.print("{s}func {s}", .{ prefix, self.src().text(name) });
        try self.typeParameters(signature.type_parameters);
        try self.text("(");
        for (signature.parameters, 0..) |parameter, position| {
            if (position != 0) try self.text(", ");
            if (parameter.named or (signature.keyword_only_from != null and position >= signature.keyword_only_from.?)) try self.text("named ");
            if (parameter.mut) try self.text("mut ");
            try self.print("{s}: ", .{self.src().text(parameter.name)});
            try self.typeText(parameter.ty, signature.type_parameters);
            if (parameter.default_value) |value| {
                try self.text(" = ");
                try self.folded(self.syntax().nodes.items[@backingInt(value)].span);
            }
        }
        try self.text(") -> ");
        try self.typeText(signature.return_type, signature.type_parameters);
        if (signature.failure_type) |failure| {
            try self.text(" fails ");
            try self.typeText(failure, signature.type_parameters);
        }
        if (declared.policy.effect_bound) |bound| {
            try self.text(" ");
            try self.folded(bound.span);
        }
        // The published ceiling: derived from the parameters and narrowed by any
        // clause the source wrote, exactly as `list-interfaces` prints it.
        try self.text(" ceiling(");
        var names: std.ArrayList(u8) = .empty;
        try interfaces.appendEffectNames(&names, self.arena, try self.index.effectiveCeiling(self.module, declared));
        try self.text(names.items);
        try self.line(")");
    }

    /// `public const NAME: T = value`; the value is part of a constant's interface.
    fn constantLine(self: *Renderer, declared: ast.Function) Error!void {
        try self.print("public const {s}: ", .{self.src().text(declared.name)});
        try self.typeText(declared.signature.return_type, &.{});
        if (self.constantValue(declared)) |span| {
            try self.text(" = ");
            try self.folded(span);
        }
        try self.text("\n");
    }

    /// The value expression of a `const` declaration: the parser stores it as
    /// the single `return` of a one-statement body.
    fn constantValue(self: *const Renderer, declared: ast.Function) ?source.Span {
        const statements = self.syntax().statements.items;
        const body = switch (statements[@backingInt(declared.body)].data) {
            .block => |block| block,
            else => return null,
        };
        if (body.len != 1) return null;
        return switch (statements[@backingInt(body[0])].data) {
            .ret => |node| self.syntax().nodes.items[@backingInt(node)].span,
            else => null,
        };
    }

    fn typeDeclaration(self: *Renderer, symbol: interfaces.Symbol) Error!void {
        const types = self.syntax().types;
        for (types.records) |record| if (record.name.start == symbol.span.start) return self.recordBlock(record);
        for (types.variants) |variant| if (variant.name.start == symbol.span.start) return self.variantsBlock(variant);
        for (types.domains) |domain| if (domain.name.start == symbol.span.start) return self.domainBlock(domain, symbol.name);
        for (types.resources) |resource| if (resource.name.start == symbol.span.start) {
            return self.print("public resource {s}: {s}\n", .{ symbol.name, self.src().text(resource.backing) });
        };
        for (types.expressions.aliases) |alias| if (alias.name.start == symbol.span.start) {
            try self.print("public type {s} = ", .{symbol.name});
            try self.typeText(alias.target, &.{});
            return self.text("\n");
        };
        return error.InternalError;
    }

    fn recordBlock(self: *Renderer, declared: ast.Record) Error!void {
        try self.print("public {s} {s}", .{ if (declared.managed) "class" else "record", self.src().text(declared.name) });
        try self.typeParameters(declared.type_parameters);
        try self.line(":");
        if (declared.fields.len == 0) try self.line(indent ++ "pass");
        for (declared.fields) |field| {
            try self.print(indent ++ "{s}: ", .{self.src().text(field.name)});
            try self.typeText(field.ty, declared.type_parameters);
            try self.text("\n");
        }
    }

    fn variantsBlock(self: *Renderer, declared: ast.Variants) Error!void {
        const keyword = if (declared.fallible) "result" else "enum";
        try self.print("public {s} {s}", .{ keyword, self.src().text(declared.name) });
        try self.typeParameters(declared.type_parameters);
        try self.line(":");
        for (declared.cases, 0..) |case, position| {
            try self.print(indent ++ "{s}", .{self.src().text(case.name)});
            if (case.payload) |payload| {
                try self.text(if (declared.fallible) ": " else "(value: ");
                try self.typeText(payload, declared.type_parameters);
                if (!declared.fallible) try self.text(")");
            } else if (case.fields.len != 0) {
                try self.text("(");
                for (case.fields, 0..) |field, field_position| {
                    if (field_position != 0) try self.text(", ");
                    try self.print("{s}: ", .{self.src().text(field.name)});
                    try self.typeText(field.ty, declared.type_parameters);
                    if (field.default_value) |value| {
                        try self.text(" = ");
                        try self.folded(self.syntax().nodes.items[@backingInt(value)].span);
                    }
                }
                try self.text(")");
            }
            try self.line(if (declared.fallible and position + 1 != declared.cases.len) "," else "");
        }
    }

    /// A domain, its codec, and its public members nested beneath it.
    fn domainBlock(self: *Renderer, declared: ast.Domain, name: []const u8) Error!void {
        try self.print("public domain {s}: ", .{name});
        try self.typeText(declared.backing, &.{});
        const members = try self.domainMembers(name);
        if (declared.codec == null and members.len == 0) return self.text("\n");
        try self.line(":");
        if (declared.codec) |codec| {
            try self.text(indent ++ "codec ");
            try self.typeText(codec.wire, &.{});
            try self.print(":\n" ++ indent ++ indent ++ "decode: {s},\n" ++ indent ++ indent ++ "encode: {s}\n", .{ self.src().text(codec.decode), self.src().text(codec.encode) });
        }
        for (members) |member| {
            try self.attributes(member, indent);
            try self.functionLine(member, indent);
        }
    }

    /// Name spans of the exported members `owner` declares, in source order.
    fn domainMembers(self: *Renderer, owner: []const u8) Error![]const source.Span {
        var members: std.ArrayList(source.Span) = .empty;
        for (self.index.units[self.module].symbols.items) |symbol| {
            if (!symbol.exported or symbol.kind != .function) continue;
            if (!std.mem.eql(u8, symbol.owner orelse continue, owner)) continue;
            try members.append(self.arena, symbol.span);
        }
        std.mem.sort(source.Span, members.items, {}, spanLess);
        return members.items;
    }

    /// `public constraint Name[P] = copy + op(...)`.
    fn constraintBlock(self: *Renderer, name: source.Span) Error!void {
        for (self.syntax().types.constraints) |declared| {
            if (declared.name.start != name.start) continue;
            const subject: []const ast.TypeParameter = &.{declared.subject};
            try self.print("public constraint {s}[{s}] = ", .{ self.src().text(name), self.src().text(declared.subject.name) });
            try self.requirements(declared.subject, subject);
            return self.text("\n");
        }
        return error.InternalError;
    }

    /// `[T: copy + length, U]` for a declaration with type parameters.
    fn typeParameters(self: *Renderer, parameters: []const ast.TypeParameter) Error!void {
        if (parameters.len == 0) return;
        try self.text("[");
        for (parameters, 0..) |parameter, position| {
            if (position != 0) try self.text(", ");
            try self.text(self.src().text(parameter.name));
            const tokens = try self.index.requirementTokens(self.module, parameter, parameters);
            if (tokens.len == 0) continue;
            try self.text(": ");
            try self.requirements(parameter, parameters);
        }
        try self.text("]");
    }

    fn requirements(self: *Renderer, parameter: ast.TypeParameter, parameters: []const ast.TypeParameter) Error!void {
        const tokens = try self.index.requirementTokens(self.module, parameter, parameters);
        for (tokens, 0..) |token, position| {
            if (position != 0) try self.text(" + ");
            try self.text(try self.surface(token, parameters));
        }
    }

    fn typeText(self: *Renderer, span: source.Span, parameters: []const ast.TypeParameter) Error!void {
        try self.text(try self.surface(try self.index.contractTypeText(self.module, span, parameters), parameters));
    }

    fn folded(self: *Renderer, span: source.Span) Error!void {
        try interfaces.appendFolded(&self.out, self.arena, std.mem.trim(u8, self.src().text(span), " \t\r\n"));
    }

    /// Rewrite a canonical descriptor into source spelling: type parameters by
    /// their declared names, this module's own declarations unqualified,
    /// capabilities by their Python names, and `module::Name` as `module.Name`.
    fn surface(self: *Renderer, canonical: []const u8, parameters: []const ast.TypeParameter) Error![]const u8 {
        var out: std.ArrayList(u8) = .empty;
        const own = self.index.project.modules.items[self.module].name;
        var cursor: usize = 0;
        while (cursor < canonical.len) {
            const start = cursor;
            if (canonical[cursor] == '$') {
                cursor += 1;
                while (cursor < canonical.len and std.ascii.isDigit(canonical[cursor])) cursor += 1;
                const position = std.fmt.parseUnsigned(usize, canonical[start + 1 .. cursor], 10) catch return error.InternalError;
                if (position >= parameters.len) return error.InternalError;
                try out.appendSlice(self.arena, self.src().text(parameters[position].name));
                continue;
            }
            if (!wordByte(canonical[cursor])) {
                try out.append(self.arena, canonical[cursor]);
                cursor += 1;
                continue;
            }
            while (cursor < canonical.len and (wordByte(canonical[cursor]) or canonical[cursor] == '.')) cursor += 1;
            const word = canonical[start..cursor];
            const own_qualified = std.mem.eql(u8, word, own) and std.mem.startsWith(u8, canonical[cursor..], "::");
            if (own_qualified) {
                cursor += 2;
                continue;
            }
            try out.appendSlice(self.arena, capabilityName(word) orelse word);
        }
        const spelled = typed.surfaceTypeText(self.arena, out.items) catch return error.OutOfMemory;
        // A callback type reads `func(int) -> int`, as a declaration writes it.
        const arrow = std.mem.replaceOwned(u8, self.arena, spelled, ")->", ") -> ") catch return error.OutOfMemory;
        return arrow;
    }
};

fn wordByte(byte: u8) bool {
    return std.ascii.isAlphanumeric(byte) or byte == '_';
}

fn spanLess(_: void, a: source.Span, b: source.Span) bool {
    return a.start < b.start;
}

/// Python spelling of a canonical capability descriptor, or null for any
/// other word.
fn capabilityName(word: []const u8) ?[]const u8 {
    const table = [_][2][]const u8{
        .{ "filesystem_cap", "Filesystem" },
        .{ "network_cap", "Network" },
        .{ "clock_cap", "Clock" },
        .{ "random_cap", "Entropy" },
        .{ "environment_cap", "Environment" },
        .{ "stream_cap", "Stream" },
        .{ "host_cap", "Host" },
    };
    for (table) |entry| if (std.mem.eql(u8, word, entry[0])) return entry[1];
    return null;
}

/// One named declaration block of an interface file: its published name
/// (`Name`, `Domain.member`, or `__doc__` for the module docstring) and the
/// exact lines that render it.
pub const Declaration = struct { name: []const u8, text: []const u8 };

/// Split interface-file text into its named declaration blocks, in file order.
/// Works on any text, so a hand-edited or older file still compares; a block
/// whose declaration line it cannot read is named by that line. Names and
/// slices borrow `bytes` or live in `arena`, which the caller releases.
pub fn declarations(arena: std.mem.Allocator, bytes: []const u8) std.mem.Allocator.Error![]const Declaration {
    var out: std.ArrayList(Declaration) = .empty;
    var blocks = std.mem.splitSequence(u8, bytes, "\n\n");
    if (blocks.next()) |preamble| {
        if (std.mem.indexOf(u8, preamble, "\"\"\"")) |at| try out.append(arena, .{ .name = docstring_name, .text = preamble[at..] });
    }
    while (blocks.next()) |raw| {
        const block = std.mem.trim(u8, raw, "\n");
        if (block.len == 0) continue;
        try splitBlock(arena, &out, block);
    }
    return out.items;
}

/// Append one block, then each domain member nested in it as `Domain.member`
/// (its indented attribute lines and `def` line). The block's own entry keeps
/// the lines before the first member: the head, fields, cases or codec.
fn splitBlock(arena: std.mem.Allocator, out: *std.ArrayList(Declaration), block: []const u8) std.mem.Allocator.Error!void {
    var lines = std.mem.splitScalar(u8, block, '\n');
    var members: std.ArrayList(Declaration) = .empty;
    var owner: ?[]const u8 = null;
    var head_end = block.len;
    var member_start: ?usize = null;
    var offset: usize = 0;
    while (lines.next()) |line| {
        defer offset += line.len + 1;
        if (owner == null) {
            if (!std.mem.startsWith(u8, line, "@")) owner = declarationName(line);
            continue;
        }
        const definition = std.mem.startsWith(u8, line, indent ++ "func ") or std.mem.startsWith(u8, line, indent ++ "def ");
        if (!definition and !std.mem.startsWith(u8, line, indent ++ "@")) continue;
        if (member_start == null) member_start = offset;
        head_end = @min(head_end, offset - 1);
        if (!definition) continue;
        const name = try std.fmt.allocPrint(arena, "{s}.{s}", .{ owner.?, declarationName(line) });
        try members.append(arena, .{ .name = name, .text = block[member_start.? .. offset + line.len] });
        member_start = null;
    }
    try out.append(arena, .{ .name = owner orelse block, .text = block[0..head_end] });
    try out.appendSlice(arena, members.items);
}

/// The published name one declaration line introduces: the identifier after
/// its keyword, the final segment of an `export a.b.Name` re-export, or the
/// whole trimmed line when it matches neither shape.
fn declarationName(raw: []const u8) []const u8 {
    const line = std.mem.trim(u8, raw, " \t\r");
    if (std.mem.startsWith(u8, line, "export ")) {
        const path = std.mem.trim(u8, line["export ".len..], " ");
        return path[(std.mem.lastIndexOfScalar(u8, path, '.') orelse return path) + 1 ..];
    }
    var rest = line;
    if (std.mem.startsWith(u8, rest, "public ")) rest = rest["public ".len..];
    const keyword_end = std.mem.indexOfScalar(u8, rest, ' ') orelse return line;
    rest = rest[keyword_end + 1 ..];
    var end: usize = 0;
    while (end < rest.len and wordByte(rest[end])) end += 1;
    return if (end == 0) line else rest[0..end];
}

/// Declaration names a regeneration adds, removes or changes, each in file order.
pub const Changes = struct {
    added: []const []const u8,
    removed: []const []const u8,
    changed: []const []const u8,

    /// Release the three name arrays; the names borrow the compared texts.
    pub fn deinit(self: Changes, allocator: std.mem.Allocator) void {
        allocator.free(self.added);
        allocator.free(self.removed);
        allocator.free(self.changed);
    }
};

/// Compare two interface texts declaration by declaration. Names borrow the
/// two texts (or the interned `Domain.member` spellings of `declarations`).
pub fn compare(allocator: std.mem.Allocator, old: []const Declaration, new: []const Declaration) std.mem.Allocator.Error!Changes {
    var added: std.ArrayList([]const u8) = .empty;
    errdefer added.deinit(allocator);
    var removed: std.ArrayList([]const u8) = .empty;
    errdefer removed.deinit(allocator);
    var changed: std.ArrayList([]const u8) = .empty;
    errdefer changed.deinit(allocator);
    for (new) |entry| {
        const previous = find(old, entry.name) orelse {
            try added.append(allocator, entry.name);
            continue;
        };
        if (!std.mem.eql(u8, previous.text, entry.text)) try changed.append(allocator, entry.name);
    }
    for (old) |entry| if (find(new, entry.name) == null) try removed.append(allocator, entry.name);
    return .{
        .added = try added.toOwnedSlice(allocator),
        .removed = try removed.toOwnedSlice(allocator),
        .changed = try changed.toOwnedSlice(allocator),
    };
}

fn find(entries: []const Declaration, name: []const u8) ?Declaration {
    for (entries) |entry| if (std.mem.eql(u8, entry.name, name)) return entry;
    return null;
}

/// Lines of context around each change in `unifiedDiff`.
const context_lines = 2;
/// Largest line-pair table the exact diff builds; a larger pair of files is
/// shown as one replacement hunk.
const max_diff_cells = 4 * 1024 * 1024;

/// Render a unified diff from `old` to `new`, labelled with `path`, keeping at
/// most `limit` hunk lines and saying how many more were cut. The caller owns
/// the returned text; identical inputs render as the empty string.
pub fn unifiedDiff(allocator: std.mem.Allocator, path: []const u8, old: []const u8, new: []const u8, limit: usize) std.mem.Allocator.Error![]u8 {
    if (std.mem.eql(u8, old, new)) return allocator.alloc(u8, 0);
    var arena_state = std.heap.ArenaAllocator.init(allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    const left = try splitLines(arena, old);
    const right = try splitLines(arena, new);
    const edits = try editScript(arena, left, right);
    var out: std.Io.Writer.Allocating = .init(allocator);
    errdefer out.deinit();
    const writer = &out.writer;
    writer.print("--- {s}\n+++ {s} (generated)\n", .{ path, path }) catch return error.OutOfMemory;
    var shown: usize = 0;
    var cut: usize = 0;
    var start: usize = 0;
    while (nextHunk(edits, start)) |hunk| : (start = hunk.end) {
        const counts = hunk.counts(edits);
        writer.print("@@ -{d},{d} +{d},{d} @@\n", .{ counts.old_start, counts.old_len, counts.new_start, counts.new_len }) catch return error.OutOfMemory;
        for (edits[hunk.start..hunk.end]) |edit| {
            if (shown == limit) {
                cut += 1;
                continue;
            }
            shown += 1;
            const marker: u8 = switch (edit.kind) {
                .keep => ' ',
                .remove => '-',
                .add => '+',
            };
            writer.print("{c}{s}\n", .{ marker, edit.line }) catch return error.OutOfMemory;
        }
    }
    if (cut != 0) writer.print("... {d} more diff lines\n", .{cut}) catch return error.OutOfMemory;
    return out.toOwnedSlice() catch error.OutOfMemory;
}

fn splitLines(allocator: std.mem.Allocator, text: []const u8) std.mem.Allocator.Error![]const []const u8 {
    var lines: std.ArrayList([]const u8) = .empty;
    if (text.len == 0) return lines.items;
    const body = if (text[text.len - 1] == '\n') text[0 .. text.len - 1] else text;
    var parts = std.mem.splitScalar(u8, body, '\n');
    while (parts.next()) |part| try lines.append(allocator, part);
    return lines.items;
}

const EditKind = enum { keep, remove, add };
/// One line of the edit script with its one-based old and new line numbers.
const Edit = struct { kind: EditKind, line: []const u8, old_line: usize, new_line: usize };

/// A longest-common-subsequence edit script from `left` to `right`. Beyond
/// `max_diff_cells` the script removes every old line and adds every new one.
fn editScript(allocator: std.mem.Allocator, left: []const []const u8, right: []const []const u8) std.mem.Allocator.Error![]const Edit {
    var edits: std.ArrayList(Edit) = .empty;
    const width = right.len + 1;
    if ((left.len + 1) * width > max_diff_cells) {
        for (left, 0..) |text, position| try edits.append(allocator, .{ .kind = .remove, .line = text, .old_line = position + 1, .new_line = 1 });
        for (right, 0..) |text, position| try edits.append(allocator, .{ .kind = .add, .line = text, .old_line = left.len + 1, .new_line = position + 1 });
        return edits.items;
    }
    // table[i * width + j] is the common-subsequence length of left[i..] and right[j..].
    const table = try allocator.alloc(u32, (left.len + 1) * width);
    @memset(table, 0);
    var i = left.len;
    while (i > 0) : (i -= 1) {
        var j = right.len;
        while (j > 0) : (j -= 1) {
            const here = (i - 1) * width + (j - 1);
            table[here] = if (std.mem.eql(u8, left[i - 1], right[j - 1])) table[i * width + j] + 1 else @max(table[i * width + (j - 1)], table[(i - 1) * width + j]);
        }
    }
    i = 0;
    var j: usize = 0;
    while (i < left.len or j < right.len) {
        const same = i < left.len and j < right.len and std.mem.eql(u8, left[i], right[j]);
        const take_remove = j == right.len or (i < left.len and table[(i + 1) * width + j] >= table[i * width + j + 1]);
        const kind: EditKind = if (same) .keep else if (take_remove) .remove else .add;
        try edits.append(allocator, .{ .kind = kind, .line = if (kind == .add) right[j] else left[i], .old_line = i + 1, .new_line = j + 1 });
        if (kind != .add) i += 1;
        if (kind != .remove) j += 1;
    }
    return edits.items;
}

/// A run of edits that holds at least one change plus its surrounding context.
const Hunk = struct {
    start: usize,
    end: usize,

    const Counts = struct { old_start: usize, old_len: usize, new_start: usize, new_len: usize };

    fn counts(self: Hunk, edits: []const Edit) Counts {
        var result: Counts = .{ .old_start = edits[self.start].old_line, .old_len = 0, .new_start = edits[self.start].new_line, .new_len = 0 };
        for (edits[self.start..self.end]) |edit| {
            if (edit.kind != .add) result.old_len += 1;
            if (edit.kind != .remove) result.new_len += 1;
        }
        // A hunk with no old (or new) lines names the line before it, as diff does.
        if (result.old_len == 0) result.old_start -= 1;
        if (result.new_len == 0) result.new_start -= 1;
        return result;
    }
};

/// The next hunk at or after `from`: a change, `context_lines` of context on
/// each side, merged with any change whose context overlaps.
fn nextHunk(edits: []const Edit, from: usize) ?Hunk {
    var first = from;
    while (first < edits.len and edits[first].kind == .keep) first += 1;
    if (first == edits.len) return null;
    var last = first;
    var cursor = first;
    while (cursor < edits.len) : (cursor += 1) {
        if (edits[cursor].kind != .keep) {
            last = cursor;
            continue;
        }
        if (cursor - last > 2 * context_lines) break;
    }
    const start = if (first > from + context_lines) first - context_lines else from;
    return .{ .start = start, .end = @min(edits.len, last + 1 + context_lines) };
}
