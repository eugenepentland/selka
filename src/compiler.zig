/// Owns one source unit and all parsed and checked data in its arena.
pub const Compilation = struct {
    arena: std.heap.ArenaAllocator,
    src: source.Source,
    diagnostics: std.ArrayList(diagnostic.Diagnostic) = .empty,
    tokens: ?[]const lexer.Token = null,
    syntax: ?ast.Program = null,
    program: ?typed.Program = null,
    /// How the checks of this unit treat a `todo[T]()` hole (`refuse` unless a build or test asks for `trap`) and whether they
    /// also check the generic functions nothing instantiates (`check` only).
    checking: diagnostic.Checking = .{},

    /// Copy the source path and bytes into a new compilation arena; release with deinit.
    pub fn init(allocator: std.mem.Allocator, path: []const u8, bytes: []const u8) std.mem.Allocator.Error!Compilation {
        var arena = std.heap.ArenaAllocator.init(allocator);
        errdefer arena.deinit();
        const src = try source.Source.init(arena.allocator(), path, bytes);
        return .{ .arena = arena, .src = src };
    }

    /// Like `init`, but mark the source as compiler-owned so it may spell reserved
    /// internal intrinsics. Only the parser's own unit tests reach this hook.
    pub fn initTrusted(allocator: std.mem.Allocator, path: []const u8, bytes: []const u8) std.mem.Allocator.Error!Compilation {
        var result = try init(allocator, path, bytes);
        result.src.trusted_intrinsics = true;
        return result;
    }

    pub fn deinit(self: *Compilation) void {
        self.arena.deinit();
    }

    /// Lazily tokenize and parse the source, retaining syntax and source diagnostics.
    pub fn parse(self: *Compilation) diagnostic.Error!void {
        return self.parseCached(null);
    }
    /// Parse through an optional persistent cache. A disk hit still rebuilds all
    /// interface, resolution and semantic state; only the lexer and parser are skipped.
    pub fn parseCached(self: *Compilation, cache: ?*frontend_cache.Cache) diagnostic.Error!void {
        if (self.syntax != null) return;
        if (cache) |disk| {
            if (try disk.lookupSyntax(self.arena.allocator(), self.src, 0)) |syntax| {
                self.syntax = syntax;
                return;
            }
        }
        var sink: diagnostic.Sink = .{ .allocator = self.arena.allocator(), .items = self.diagnostics, .hole_mode = self.checking.holes, .template_probes = self.checking.template_probes };
        defer self.diagnostics = sink.items;
        self.tokens = try lexer.lex(sink.allocator, self.src.bytes, &sink);
        var p: parser.Parser = .{ .src = self.src, .storage = self.arena.allocator(), .tokens = self.tokens.?, .sink = &sink };
        self.syntax = try p.parse();
        if (cache) |disk| try disk.rememberSyntax(self.src, 0, self.syntax.?);
    }

    /// Allocate the canonical formatting of this unit. A file that opens with a
    /// `module` header or an `import` directive is a module file, so it is
    /// formatted with the module grammar rather than rejected at its first word.
    ///
    /// The text is returned only after it has been parsed again and found to hold the syntax its input held
    /// (`verifyFormatted`); otherwise the result is `error.FormatRejected` and nothing is returned.
    pub fn format(self: *Compilation, allocator: std.mem.Allocator) FormatError![]u8 {
        if (opensAsModule(self.src.bytes)) return self.formatModule(allocator);
        const original = self.src;
        self.src = self.formattingSource();
        defer self.src = original;
        try self.parse();
        const formatted = try @import("formatter.zig").format(allocator, self.src.bytes, self.tokens.?, self.syntax.?);
        errdefer allocator.free(formatted);
        try self.verifyFormatted(allocator, formatted, .{ .tokens = self.tokens.?, .syntax = self.syntax.?, .module = false });
        return formatted;
    }

    /// Parse module syntax and allocate its canonical formatting with the caller allocator, held to the same check as `format`.
    pub fn formatModule(self: *Compilation, allocator: std.mem.Allocator) FormatError![]u8 {
        const parsed = try self.parseModuleSyntax();
        const formatted = try @import("formatter.zig").format(allocator, self.src.bytes, parsed.tokens, parsed.syntax);
        errdefer allocator.free(formatted);
        try self.verifyFormatted(allocator, formatted, .{ .tokens = parsed.tokens, .syntax = parsed.syntax, .module = true });
        return formatted;
    }

    /// The tokens and syntax of a unit parsed as a module.
    pub const ModuleParse = struct { tokens: []const lexer.Token, syntax: ast.Program };

    /// Lex and parse this unit's source as a module (its header and import directives, then its declarations).
    pub fn parseModuleSyntax(self: *Compilation) diagnostic.Error!ModuleParse {
        var sink: diagnostic.Sink = .{ .allocator = self.arena.allocator(), .items = self.diagnostics, .hole_mode = self.checking.holes, .template_probes = self.checking.template_probes };
        defer self.diagnostics = sink.items;
        const tokens = try lexer.lex(sink.allocator, self.src.bytes, &sink);
        var p: parser.Parser = .{ .src = self.formattingSource(), .storage = self.arena.allocator(), .tokens = tokens, .sink = &sink };
        return .{ .tokens = tokens, .syntax = try p.parseModule() };
    }

    /// What `verifyFormatted` compares the formatted text with: the tokens and syntax this unit's source parsed to, and whether
    /// it was parsed as a module.
    pub const FormatInput = struct { tokens: []const lexer.Token, syntax: ast.Program, module: bool };

    /// The formatter's safety net. Parse `formatted` again, as the module or program the input was, and compare its syntax with
    /// the input's, ignoring layout and comments (`format_verify.judge`). Text that does not parse, or parses to other syntax,
    /// is refused with an `E_FORMAT_VERIFY` diagnostic at the input line of the construct that changed, and the result is
    /// `error.FormatRejected`: nothing may be written from it.
    pub fn verifyFormatted(self: *Compilation, allocator: std.mem.Allocator, formatted: []const u8, input: FormatInput) FormatError!void {
        // Text that is the input's own bytes parses to the input's own syntax: a source that is already canonical, the usual
        // case of `fmt --check`, has nothing to compare and costs nothing.
        if (std.mem.eql(u8, formatted, self.src.bytes)) return;
        var again = try Compilation.init(allocator, self.src.path, formatted);
        defer again.deinit();
        again.src.trusted_intrinsics = self.formattingSource().trusted_intrinsics;
        again.checking = self.checking;
        var output: format_verify.Parse = .{ .src = again.src, .module = input.module };
        if (input.module) {
            if (again.parseModuleSyntax()) |parsed| {
                output.tokens = parsed.tokens;
                output.syntax = parsed.syntax;
            } else |err| switch (err) {
                error.SourceError => output.failure = again.diagnostics.items[0],
                else => return err,
            }
        } else {
            if (again.parse()) {
                output.syntax = again.syntax;
            } else |err| switch (err) {
                error.SourceError => output.failure = again.diagnostics.items[0],
                else => return err,
            }
            output.tokens = again.tokens;
        }
        const finding = (try format_verify.judge(self.arena.allocator(), .{ .src = self.src, .tokens = input.tokens, .syntax = input.syntax, .module = input.module }, output)) orelse return;
        try self.diagnostics.append(self.arena.allocator(), .{ .code = format_verify.code, .span = finding.input, .message = finding.message });
        return error.FormatRejected;
    }

    // Project checking selects embedded standard modules. Formatting reads
    // disk bytes, so grant that context only to a complete name/byte match.
    fn formattingSource(self: *const Compilation) source.Source {
        var src = self.src;
        if (@import("standard_library.zig").source(std.fs.path.basename(src.path))) |embedded| {
            src.trusted_intrinsics = src.trusted_intrinsics or std.mem.eql(u8, src.bytes, embedded);
        }
        return src;
    }

    /// Parse one module or single-file program and allocate its declaration listing.
    pub fn listDeclarations(self: *Compilation, allocator: std.mem.Allocator) declarations.Error![]u8 {
        var sink: diagnostic.Sink = .{ .allocator = self.arena.allocator(), .items = self.diagnostics, .hole_mode = self.checking.holes, .template_probes = self.checking.template_probes };
        defer self.diagnostics = sink.items;
        const tokens = try lexer.lex(sink.allocator, self.src.bytes, &sink);
        return declarations.render(allocator, &self.arena, self.src, tokens, &sink);
    }

    /// Lazily type-check parsed syntax and retain the checked program.
    pub fn check(self: *Compilation) diagnostic.Error!void {
        return self.checkWithCache(null);
    }

    /// Build uncached typed trees for the developer ownership census and Core audit.
    pub fn checkForOwnershipAudit(self: *Compilation, library: bool) diagnostic.Error!void {
        std.debug.assert(self.program == null);
        try self.parse();
        var sink: diagnostic.Sink = .{
            .allocator = self.arena.allocator(),
            .items = self.diagnostics,
            .hole_mode = self.checking.holes,
        };
        defer self.diagnostics = sink.items;
        self.program = if (library and !self.declaresMain())
            try sema.checkLibraryProgram(sink.allocator, self.src, self.syntax.?, &sink, null)
        else
            try sema.check(sink.allocator, self.src, self.syntax.?, &sink);
    }
    /// Check through an optional persistent syntax cache. Declaration, interface
    /// and whole-program validation always run; only source lexing and parsing
    /// may be skipped.
    pub fn checkWithFrontend(self: *Compilation, cache: ?*frontend_cache.Cache) diagnostic.Error!void {
        if (self.program != null) return;
        for (self.diagnostics.items) |item| if (item.severity == .err) return error.SourceError;
        try self.parseCached(cache);
        var sink: diagnostic.Sink = .{ .allocator = self.arena.allocator(), .items = self.diagnostics, .hole_mode = self.checking.holes, .template_probes = self.checking.template_probes };
        defer self.diagnostics = sink.items;
        self.program = try sema.checkCached(sink.allocator, self.src, self.syntax.?, &sink, null, null);
    }
    /// Reuse independently owned checked bodies after supported source edits.
    pub fn checkWithCache(self: *Compilation, cache: ?*semantic_cache.Cache) diagnostic.Error!void {
        if (self.program != null) return;
        for (self.diagnostics.items) |item| if (item.severity == .err) return error.SourceError;
        try self.parse();
        var sink: diagnostic.Sink = .{ .allocator = self.arena.allocator(), .items = self.diagnostics, .hole_mode = self.checking.holes, .template_probes = self.checking.template_probes };
        defer self.diagnostics = sink.items;
        self.program = try sema.checkCached(sink.allocator, self.src, self.syntax.?, &sink, null, cache);
    }

    /// Whether the unit declares a free function named `main`, whatever its signature.
    pub fn declaresMain(self: *const Compilation) bool {
        return sema.declaresMain(self.src, self.syntax.?);
    }

    /// Return library trees for backend validation without retaining an executable.
    pub fn checkLibraryProgram(self: *Compilation) diagnostic.Error!typed.Program {
        for (self.diagnostics.items) |item| if (item.severity == .err) return error.SourceError;
        try self.parse();
        var sink: diagnostic.Sink = .{ .allocator = self.arena.allocator(), .items = self.diagnostics, .hole_mode = self.checking.holes, .template_probes = self.checking.template_probes };
        defer self.diagnostics = sink.items;
        return sema.checkLibraryProgram(sink.allocator, self.src, self.syntax.?, &sink, null);
    }

    /// After a strict check failed only with typed holes, the same unit checked with every hole as a typed
    /// node (`HoleMode.trap`), so the ownership phase still sees the whole program. What the holes hid is appended to
    /// `diagnostics`, so call this before rendering them: the errors of a second check that fails too (an unread capability
    /// parameter is found by a pass that runs only after every body checked), and the warnings of that check, which a
    /// refused check never reaches. After a check whose bodies failed otherwise, the unit checked with each failed body stood
    /// in (`HoleMode.recover`, `typed.recoveredStandIn`), whose findings the refused check already reports, so the ownership
    /// of the bodies that checked is still validated (F-RC-214). Null when no body could be recovered.
    pub fn holeProgram(self: *Compilation, library: bool) error{OutOfMemory}!?typed.Program {
        const holes = diagnostic.holesOnly(self.diagnostics.items);
        const syntax = self.syntax orelse return null;
        var sink: diagnostic.Sink = .{ .allocator = self.arena.allocator(), .hole_mode = if (holes) .trap else .recover };
        defer sink.deinit();
        const checked = if (library) sema.checkLibraryProgram(sink.allocator, self.src, syntax, &sink, null) else sema.checkCached(sink.allocator, self.src, syntax, &sink, null, null);
        const program: ?typed.Program = checked catch |err| switch (err) {
            error.OutOfMemory => return error.OutOfMemory,
            else => null,
        };
        if (holes) for (sink.items.items) |item| if (!diagnostic.holds(self.diagnostics.items, item)) try self.diagnostics.append(self.arena.allocator(), item);
        return program;
    }
    /// Type-check a unit that has no `main` as a library: every declaration and body,
    /// effects and public type boundaries, with no executable entry. The checked tree is
    /// discarded, so `program` stays null and no caller can lower or run the result.
    pub fn checkLibrary(self: *Compilation) diagnostic.Error!void {
        for (self.diagnostics.items) |item| if (item.severity == .err) return error.SourceError;
        try self.parse();
        var sink: diagnostic.Sink = .{ .allocator = self.arena.allocator(), .items = self.diagnostics, .hole_mode = self.checking.holes, .template_probes = self.checking.template_probes };
        defer self.diagnostics = sink.items;
        try sema.checkLibrary(sink.allocator, self.src, self.syntax.?, &sink, null);
    }
};

