//! `mylang api`: write or check the generated interface file beside every
//! project module, and the same comparison `mylang check` reports as
//! `E_INTERFACE_FILE_STALE` when `mylang.json` sets `interface_files`.
//!
//! Rendering lives in the compiler (`interface_files.zig`); this file owns the
//! host side: reading the checked-in files, finding orphaned ones, writing and
//! deleting, and the text and JSON reports.
const std = @import("std");
const interfaces = @import("interfaces.zig");
const interface_files = @import("interface_files.zig");

/// Largest interface file read back for comparison.
const max_file_bytes = 16 * 1024 * 1024;
/// Hunk lines shown per module in the `--check` text report.
const diff_line_limit = 40;
/// Directories never searched for orphaned interface files.
const skipped_directories = [_][]const u8{ ".git", ".mylang-cache", ".zig-cache", "zig-out", "node_modules" };

/// What `mylang api` does with the files it compares.
pub const Mode = enum { write, check };

/// One `mylang api` request: the entry's project root (the directory module
/// paths are relative to), the entry as the user spelled it for the hint, the
/// mode, and whether to report JSON.
pub const Request = struct { io: std.Io, root: []const u8, entry: []const u8, mode: Mode, json: bool };

/// The command's exit status and the report it prints on stdout.
pub const Outcome = struct { status: u8, report: []u8 };

/// How one interface file compares with its regenerated text.
pub const State = enum { current, missing, stale, orphaned };

/// One compared file: the module it belongs to, its root-relative path, its
/// state, and the checked-in and regenerated bytes (empty when absent).
pub const Entry = struct { module: []const u8, path: []const u8, state: State, old: []const u8, new: []const u8 };

/// Host failures reading, writing or deleting interface files.
pub const Error = interface_files.Error || error{HostIo};

/// Compare every project module's interface file with its regenerated text.
/// Embedded standard modules have none. Everything lives in `arena`.
pub fn collect(arena: std.mem.Allocator, io: std.Io, root: []const u8, index: *interfaces.Index) Error![]Entry {
    var entries: std.ArrayList(Entry) = .empty;
    for (index.project.order.items) |module| {
        const loaded = index.project.modules.items[module];
        if (!interface_files.projectModule(loaded.src)) continue;
        const path = try interface_files.apiPath(arena, loaded.src.path);
        const new = try interface_files.render(arena, index, module);
        const old = try readOptional(arena, io, try std.fs.path.join(arena, &.{ root, path }));
        const state: State = if (old == null) .missing else if (std.mem.eql(u8, old.?, new)) .current else .stale;
        try entries.append(arena, .{ .module = loaded.name, .path = path, .state = state, .old = old orelse "", .new = new });
    }
    return entries.items;
}

/// Run `mylang api` against an indexed project.
pub fn run(allocator: std.mem.Allocator, request: Request, index: *interfaces.Index) Error!Outcome {
    var arena_state = std.heap.ArenaAllocator.init(allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    var entries: std.ArrayList(Entry) = .empty;
    try entries.appendSlice(arena, try collect(arena, request.io, request.root, index));
    try appendOrphans(arena, request.io, request.root, &entries);
    if (request.mode == .write) try apply(arena, request, entries.items);
    const report = if (request.json) try jsonReport(arena, request.mode, entries.items) else try textReport(arena, request, entries.items);
    const changed = outOfDate(entries.items) != 0;
    const owned = try allocator.dupe(u8, report);
    return .{
        .status = if (request.mode == .check and changed) 1 else 0,
        .report = owned,
    };
}

/// The `E_INTERFACE_FILE_STALE` diagnostics for a project that opted in, one
/// line per missing or stale file, or null when every file is current.
pub fn staleDiagnostics(allocator: std.mem.Allocator, io: std.Io, root: []const u8, entry: []const u8, index: *interfaces.Index) Error!?[]u8 {
    var arena_state = std.heap.ArenaAllocator.init(allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    const entries = try collect(arena, io, root, index);
    if (outOfDate(entries) == 0) return null;
    var out: std.ArrayList(u8) = .empty;
    for (entries) |item| {
        if (item.state == .current) continue;
        try out.print(arena, "{s}:1:1: error[E_INTERFACE_FILE_STALE]: the interface file of module `{s}` is {s}; run `mylang api {s} --write` and review its diff\n", .{
            item.path, item.module, @tagName(item.state), entry,
        });
    }
    const owned = try allocator.dupe(u8, out.items);
    return owned;
}

fn outOfDate(entries: []const Entry) usize {
    var count: usize = 0;
    for (entries) |item| count += @intFromBool(item.state != .current);
    return count;
}

fn countState(entries: []const Entry, state: State) usize {
    var count: usize = 0;
    for (entries) |item| count += @intFromBool(item.state == state);
    return count;
}

fn readOptional(arena: std.mem.Allocator, io: std.Io, path: []const u8) Error!?[]const u8 {
    return std.Io.Dir.cwd().readFileAlloc(io, path, arena, .limited(max_file_bytes)) catch |err| switch (err) {
        error.OutOfMemory => error.OutOfMemory,
        error.FileNotFound => null,
        else => error.HostIo,
    };
}

/// Append every generated `.api` file under the root that no loaded module
/// owns and whose `.my` source no longer exists. A file whose source still
/// exists may belong to another entry's graph, so it is left alone, and a file
/// without the generated header was written by hand and is never touched.
fn appendOrphans(arena: std.mem.Allocator, io: std.Io, root: []const u8, entries: *std.ArrayList(Entry)) Error!void {
    var directory = std.Io.Dir.cwd().openDir(io, root, .{ .iterate = true }) catch return error.HostIo;
    defer directory.close(io);
    var walker = directory.walk(arena) catch return error.OutOfMemory;
    defer walker.deinit();
    var found: std.ArrayList(Entry) = .empty;
    while (walker.next(io) catch return error.HostIo) |item| {
        if (item.kind == .directory and skipped(item.basename)) {
            walker.leave(io);
            continue;
        }
        if (item.kind != .file or !std.mem.endsWith(u8, item.path, interface_files.extension)) continue;
        const path = try arena.dupe(u8, item.path);
        if (listed(entries.items, path)) continue;
        const bytes = (try readOptional(arena, io, try std.fs.path.join(arena, &.{ root, path }))) orelse continue;
        if (!interface_files.generated(bytes)) continue;
        const source_path = try std.mem.concat(arena, u8, &.{ path[0 .. path.len - interface_files.extension.len], ".my" });
        if (try readOptional(arena, io, try std.fs.path.join(arena, &.{ root, source_path })) != null) continue;
        const module = interface_files.declaredModule(bytes) orelse path;
        try found.append(arena, .{ .module = module, .path = path, .state = .orphaned, .old = bytes, .new = "" });
    }
    // Directory iteration order is the file system's; report orphans by path.
    std.mem.sort(Entry, found.items, {}, pathLess);
    try entries.appendSlice(arena, found.items);
}

fn skipped(name: []const u8) bool {
    for (skipped_directories) |directory| if (std.mem.eql(u8, name, directory)) return true;
    return false;
}

fn listed(entries: []const Entry, path: []const u8) bool {
    for (entries) |item| if (std.mem.eql(u8, item.path, path)) return true;
    return false;
}

fn pathLess(_: void, a: Entry, b: Entry) bool {
    return std.mem.lessThan(u8, a.path, b.path);
}

/// Write every missing or stale file and delete every orphan.
fn apply(arena: std.mem.Allocator, request: Request, entries: []const Entry) Error!void {
    for (entries) |item| {
        const absolute = try std.fs.path.join(arena, &.{ request.root, item.path });
        switch (item.state) {
            .current => {},
            .missing, .stale => try writeFile(request.io, absolute, item.new),
            .orphaned => std.Io.Dir.cwd().deleteFile(request.io, absolute) catch return error.HostIo,
        }
    }
}

/// Write one interface file, creating its directory when the module's source
/// did not come from disk.
fn writeFile(io: std.Io, absolute: []const u8, bytes: []const u8) Error!void {
    if (std.fs.path.dirname(absolute)) |parent| std.Io.Dir.cwd().createDirPath(io, parent) catch return error.HostIo;
    std.Io.Dir.cwd().writeFile(io, .{ .sub_path = absolute, .data = bytes }) catch return error.HostIo;
}

fn textReport(arena: std.mem.Allocator, request: Request, entries: []const Entry) Error![]const u8 {
    var out: std.ArrayList(u8) = .empty;
    var files: usize = 0;
    for (entries) |item| {
        files += @intFromBool(item.state != .orphaned);
        if (item.state == .current) continue;
        if (request.mode == .write) {
            const verb = if (item.state == .orphaned) "deleted" else "wrote";
            try out.print(arena, "api: {s} {s} ({s})\n", .{ verb, item.path, item.module });
            continue;
        }
        try out.print(arena, "api: {s} is {s} ({s})\n", .{ item.module, @tagName(item.state), item.path });
        try out.appendSlice(arena, try interface_files.unifiedDiff(arena, item.path, item.old, item.new, diff_line_limit));
    }
    const changed = outOfDate(entries);
    if (changed == 0) {
        try out.print(arena, "api: {d} interface files current\n", .{files});
    } else if (request.mode == .write) {
        const deleted = countState(entries, .orphaned);
        try out.print(arena, "api: {d} interface files current ({d} written, {d} deleted)\n", .{ files, changed - deleted, deleted });
    } else {
        try out.print(arena, "api: {d} interface files out of date; run `mylang api {s} --write`\n", .{ changed, request.entry });
    }
    return out.items;
}

/// One changed module in the `interface-files-v1` JSON report.
const ModuleReport = struct {
    module: []const u8,
    path: []const u8,
    state: []const u8,
    added: []const []const u8,
    removed: []const []const u8,
    changed: []const []const u8,
};

/// The `interface-files-v1` document `--json` prints.
const Report = struct {
    version: []const u8 = "interface-files-v1",
    mode: []const u8,
    status: []const u8,
    files: usize,
    modules: []const ModuleReport,
};

fn jsonReport(arena: std.mem.Allocator, mode: Mode, entries: []const Entry) Error![]const u8 {
    var modules: std.ArrayList(ModuleReport) = .empty;
    var files: usize = 0;
    for (entries) |item| {
        files += @intFromBool(item.state != .orphaned);
        if (item.state == .current) continue;
        const changes = try interface_files.compare(
            arena,
            try interface_files.declarations(arena, item.old),
            try interface_files.declarations(arena, item.new),
        );
        try modules.append(arena, .{
            .module = item.module,
            .path = item.path,
            .state = @tagName(item.state),
            .added = changes.added,
            .removed = changes.removed,
            .changed = changes.changed,
        });
    }
    const status = if (modules.items.len == 0) "current" else if (mode == .write) "updated" else "stale";
    const text = try std.json.Stringify.valueAlloc(arena, Report{ .mode = @tagName(mode), .status = status, .files = files, .modules = modules.items }, .{});
    return std.mem.concat(arena, u8, &.{ text, "\n" });
}
