test "declaration comparison names added, removed and changed declarations and domain members" {
    var arena_state = std.heap.ArenaAllocator.init(t.allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();
    const edited =
        \\# generated by selka api; do not edit
        \\module pkg.units
        \\"""Units."""
        \\
        \\public domain Metres: int:
        \\    @requires(value > 0)
        \\    func of(value: int) -> Metres effects() ceiling()
        \\    func feet(m: Metres) -> int effects() ceiling()
        \\
        \\public const SCALE: int = 3
        \\
    ;
    const old = try interface_files.declarations(arena, units_interface);
    try t.expectEqual(@as(usize, 3), old.len);
    try t.expectEqualStrings("Metres", old[0].name);
    try t.expectEqualStrings("public domain Metres: int:", old[0].text);
    try t.expectEqualStrings("Metres.of", old[1].name);
    try t.expectEqualStrings("    @requires(value >= 0)\n    func of(value: int) -> Metres effects() ceiling()", old[1].text);
    const changes = try interface_files.compare(arena, old, try interface_files.declarations(arena, edited));
    try t.expectEqual(@as(usize, 3), changes.added.len);
    try t.expectEqualStrings(interface_files.docstring_name, changes.added[0]);
    try t.expectEqualStrings("Metres.feet", changes.added[1]);
    try t.expectEqualStrings("SCALE", changes.added[2]);
    try t.expectEqual(@as(usize, 1), changes.removed.len);
    try t.expectEqualStrings("Metres.value", changes.removed[0]);
    try t.expectEqual(@as(usize, 1), changes.changed.len);
    try t.expectEqualStrings("Metres.of", changes.changed[0]);
}

// spec-case: API-FILE-2
test "the check diff is a short unified diff with context and a line cap" {
    const old = "a\nb\nc\nd\ne\nf\ng\n";
    const new = "a\nb\nc\nD\ne\nf\ng\nh\n";
    const diff = try interface_files.unifiedDiff(t.allocator, "x.api", old, new, 40);
    defer t.allocator.free(diff);
    try t.expectEqualStrings("--- x.api\n+++ x.api (generated)\n@@ -2,6 +2,7 @@\n b\n c\n-d\n+D\n e\n f\n g\n+h\n", diff);
    const capped = try interface_files.unifiedDiff(t.allocator, "x.api", old, new, 3);
    defer t.allocator.free(capped);
    try t.expect(std.mem.endsWith(u8, capped, " b\n c\n-d\n... 5 more diff lines\n"));
    const same = try interface_files.unifiedDiff(t.allocator, "x.api", old, old, 40);
    defer t.allocator.free(same);
    try t.expectEqual(@as(usize, 0), same.len);
    const created = try interface_files.unifiedDiff(t.allocator, "x.api", "", "a\n", 40);
    defer t.allocator.free(created);
    try t.expectEqualStrings("--- x.api\n+++ x.api (generated)\n@@ -0,0 +1,1 @@\n+a\n", created);
}

/// Write `bytes` at `path` inside the temporary project, creating directories.
fn writeTmp(dir: *std.testing.TmpDir, path: []const u8, bytes: []const u8) !void {
    if (std.fs.path.dirname(path)) |parent| try dir.dir.createDirPath(t.io, parent);
    try dir.dir.writeFile(t.io, .{ .sub_path = path, .data = bytes });
}

/// Run `selka api` over the in-memory fixture with `root` as its project root.
fn runApi(root: []const u8, mode: api_files.Mode, json: bool) !api_files.Outcome {
    var files: Files = .{ .entries = &.{
        .{ .path = source_names.entry, .bytes = entry },
        .{ .path = shapes_path, .bytes = shapes },
        .{ .path = "pkg/units.selka", .bytes = units },
    } };
    var project = graph.Project.init(t.allocator);
    defer project.deinit();
    try project.load(files.provider(), "main", .{});
    var index = try interfaces.build(&project);
    return api_files.run(t.allocator, .{ .io = t.io, .root = root, .entry = source_names.entry, .mode = mode, .json = json }, &index);
}

// spec: API-FILE-2
test "api --write writes missing files and deletes generated orphans; --check then passes" {
    var temp = t.tmpDir(.{});
    defer temp.cleanup();
    const root = try temp.dir.realPathFileAlloc(t.io, ".", t.allocator);
    defer t.allocator.free(root);
    try writeTmp(&temp, "pkg/gone.api", "# generated by selka api; do not edit\nmodule pkg.gone\n\npublic func f() -> int ceiling()\n");
    try writeTmp(&temp, "pkg/notes.api", "hand written, never touched\n");
    try writeTmp(&temp, "pkg/kept.api", "# generated by selka api; do not edit\n");
    try writeTmp(&temp, "pkg/kept.selka", "");
    try writeTmp(&temp, ".hidden/gone.api", "# generated by selka api; do not edit\n");

    const checked = try runApi(root, .check, false);
    defer t.allocator.free(checked.report);
    try t.expectEqual(@as(u8, 1), checked.status);
    try t.expect(std.mem.indexOf(u8, checked.report, "api: pkg.shapes is missing (pkg/shapes.api)\n--- pkg/shapes.api\n+++ pkg/shapes.api (generated)\n") != null);
    try t.expect(std.mem.indexOf(u8, checked.report, "api: pkg.gone is orphaned (pkg/gone.api)\n") != null);
    try t.expect(std.mem.endsWith(u8, checked.report, "api: 4 interface files out of date; run `selka api main.selka --write`\n"));

    const written = try runApi(root, .write, false);
    defer t.allocator.free(written.report);
    try t.expectEqual(@as(u8, 0), written.status);
    try t.expect(std.mem.endsWith(u8, written.report, "api: 3 interface files current (3 written, 1 deleted)\n"));
    const on_disk = try temp.dir.readFileAlloc(t.io, "pkg/shapes.api", t.allocator, .limited(1 << 20));
    defer t.allocator.free(on_disk);
    try t.expectEqualStrings(shapes_interface, on_disk);
    try t.expectError(error.FileNotFound, temp.dir.statFile(t.io, "pkg/gone.api", .{}));
    _ = try temp.dir.statFile(t.io, "pkg/notes.api", .{});
    _ = try temp.dir.statFile(t.io, "pkg/kept.api", .{});
    _ = try temp.dir.statFile(t.io, ".hidden/gone.api", .{});

    const current = try runApi(root, .check, false);
    defer t.allocator.free(current.report);
    try t.expectEqual(@as(u8, 0), current.status);
    try t.expectEqualStrings("api: 3 interface files current\n", current.report);
}

