/// Render one module of the three-module fixture whose `pkg/shapes.selka` is
/// `shapes_source`. The caller owns the text.
fn renderShapes(allocator: std.mem.Allocator, shapes_source: []const u8, module: []const u8) ![]u8 {
    var files: Files = .{ .entries = &.{
        .{ .path = source_names.entry, .bytes = entry },
        .{ .path = shapes_path, .bytes = shapes_source },
        .{ .path = "pkg/units.selka", .bytes = units },
    } };
    var project = graph.Project.init(allocator);
    defer project.deinit();
    try project.load(files.provider(), "main", .{});
    var index = try interfaces.build(&project);
    return interface_files.render(allocator, &index, project.names.get(module).?);
}

/// Render `pkg.shapes` after replacing `from` with `to` in its source.
fn renderEdited(allocator: std.mem.Allocator, from: []const u8, to: []const u8) ![]u8 {
    try t.expect(std.mem.indexOf(u8, shapes, from) != null);
    const edited = try std.mem.replaceOwned(u8, allocator, shapes, from, to);
    defer allocator.free(edited);
    return renderShapes(allocator, edited, shapes_module);
}

