//! Deterministic Markdown presentation of the overview-v1 fact document.
//!
//! One rendered set has two shapes from the same facts: a short summary a person
//! reads top to bottom, and one reference file per module to look things up in.
const std = @import("std");
const types = @import("overview_types.zig");
const decision = @import("release_decisions.zig");
const paths = @import("overview_paths.zig");
const collect = @import("overview_collect.zig");
const facts = @import("overview_facts.zig");

/// Render the summary; returned bytes belong to the caller.
pub fn render(a: std.mem.Allocator, document: types.Document) std.mem.Allocator.Error![]u8 {
    var out: Writer = .{ .a = a, .document = document, .base = document.releases.overview_path };
    try out.print("# {s}: overview\n\n<!-- generated by `selka overview .`; do not edit -->\n\n", .{document.title});
    try out.prose(document.summary);
    try out.contents();
    try out.glance();
    try out.modules();
    try out.renderAuthority();
    try out.changes();
    try out.declarations();
    try out.history();
    return out.bytes.toOwnedSlice(a);
}

/// Render one module's reference; returned bytes belong to the caller.
pub fn renderReference(a: std.mem.Allocator, document: types.Document, module: types.Module) std.mem.Allocator.Error![]u8 {
    var out: Writer = .{
        .a = a,
        .document = document,
        .base = try paths.referencePath(a, document.releases.overview_path, module.name),
    };
    try out.print("# {s}: reference\n\n<!-- generated by `selka overview .`; do not edit -->\n\n", .{module.name});
    try out.text("[Project summary](");
    try out.text(try out.destination(document.releases.overview_path));
    try out.text(")\n\n");
    try out.prose(module.doc);
    try out.moduleLinks("Imports", module.imports);
    try out.moduleLinks("Imported by", module.importers);
    if (module.private_functions != 0) try out.print("Private functions: {d}.\n\n", .{module.private_functions});
    for (module.declarations) |declaration| try out.renderDeclaration(declaration);
    return out.bytes.toOwnedSlice(a);
}

/// Whether a generated line states nothing but an empty fact, such as
/// `Contracts: none.` or `Status: implemented.` Such lines are never rendered.
pub fn noneFact(line: []const u8) bool {
    const trimmed = std.mem.trim(u8, line, " \t\r-*");
    const colon = std.mem.lastIndexOfScalar(u8, trimmed, ':');
    const value = std.mem.trim(u8, if (colon) |at| trimmed[at + 1 ..] else trimmed, " \t.*_`");
    if (std.mem.eql(u8, value, "none") or std.mem.eql(u8, value, "nothing")) return true;
    if (std.mem.eql(u8, value, "implemented") and colon != null) return true;
    return std.mem.eql(u8, trimmed, "No releases recorded.") or
        std.mem.eql(u8, trimmed, "No public interface changes.");
}

const Writer = struct {
    a: std.mem.Allocator,
    document: types.Document,
    /// Root-relative path of the file being rendered; links are relative to it.
    base: []const u8,
    bytes: std.ArrayList(u8) = .empty,

    fn text(self: *Writer, value: []const u8) !void {
        try self.bytes.appendSlice(self.a, value);
    }
    fn print(self: *Writer, comptime format: []const u8, args: anytype) !void {
        try self.bytes.print(self.a, format, args);
    }
    fn contents(self: *Writer) !void {
        try self.text("## Contents\n\n- [At a glance](#at-a-glance)\n- [Modules](#modules)\n");
        if (self.document.releases.authority.len != 0) try self.text("- [Authority](#authority)\n");
        if (self.hasChanges()) try self.print("- [Changes since {s}](#changes)\n", .{self.document.releases.since});
        try self.text("- [Public declarations](#public-declarations)\n");
        for (self.document.modules) |module| try self.print("  - [{s}](#module-{s})\n", .{ module.name, try anchor(self.a, module.name) });
        if (self.document.releases.history.len != 0) try self.text("- [Releases](#releases)\n");
        try self.text("\n");
    }
    fn glance(self: *Writer) !void {
        const c = self.document.counts;
        try self.text("## At a glance\n\n| Fact | Value |\n| --- | --- |\n");
        try self.print("| Modules | {d} |\n", .{c.modules});
        try self.print("| Public functions | {d}", .{c.functions.total});
        if (c.functions.with_examples != 0 or c.functions.waived != 0) {
            try self.print(" ({d} with examples, {d} waived)", .{ c.functions.with_examples, c.functions.waived });
        }
        try self.text(" |\n");
        try self.print("| Public types | {d} |\n", .{c.types});
        try self.print("| Tests | {d} |\n", .{c.tests});
        if (c.examples != 0) try self.print("| Docstring examples | {d} |\n", .{c.examples});
        if (c.holes != 0) try self.print("| Open holes | {d} |\n", .{c.holes});
        try self.text("\n");
    }
    fn modules(self: *Writer) !void {
        try self.text("## Modules\n\n| Module | Purpose | Imports | Public | Private |\n| --- | --- | --- | --- | --- |\n");
        for (self.document.modules) |module| {
            try self.text("| [");
            try self.text(try cell(self.a, module.name));
            try self.text("](");
            try self.text(try self.destination(try paths.referencePath(self.a, self.document.releases.overview_path, module.name)));
            try self.print(") | {s} | ", .{try cell(self.a, collect.firstSentence(module.doc))});
            try self.inlineModules(module.imports);
            try self.print(" | {d} | {d} |\n", .{ module.declarations.len, module.private_functions });
        }
        try self.text("\n");
    }
    fn renderAuthority(self: *Writer) !void {
        if (self.document.releases.authority.len == 0) return;
        try self.text("## Authority\n\n| Capability | Public functions |\n| --- | --- |\n");
        for (self.document.releases.authority) |item| {
            try self.print("| {s} | ", .{item.type});
            try self.declarationNames(item.functions);
            try self.text(" |\n");
        }
        try self.text("\n");
    }
    fn hasChanges(self: *Writer) bool {
        if (self.document.releases.changes.len != 0) return true;
        for (self.document.releases.decisions) |item| if (item.pending) return true;
        return false;
    }
    fn changes(self: *Writer) !void {
        if (!self.hasChanges()) return;
        try self.print("<a id=\"changes\"></a>\n\n## Changes since {s}\n\n", .{self.document.releases.since});
        if (self.document.releases.changes.len != 0) {
            try self.text("| Declaration | Change | Decision |\n| --- | --- | --- |\n");
            for (self.document.releases.changes) |change| {
                try self.text("| ");
                try self.appendName(change.name);
                try self.print(" | {s} | ", .{change.kind});
                try self.decisionLinks(change.decisions);
                try self.text(" |\n");
            }
            try self.text("\n");
        }
        for (self.document.releases.decisions) |item| {
            if (!item.pending) continue;
            try self.print("### {s}", .{decisionTitle(item)});
            if (item.metadata.date) |date| try self.print(" ({s})", .{date});
            try self.print("\n\n[Decision]({s})\n\n", .{try self.decisionPath(item.path)});
            try self.text("Why: ");
            try self.prose(item.metadata.why);
            if (item.metadata.rejected) |rejected| {
                try self.text("Rejected: ");
                try self.prose(rejected);
            }
            try self.extraProse(item.body);
        }
    }
    fn declarations(self: *Writer) !void {
        try self.text("<a id=\"public-declarations\"></a>\n\n## Public declarations\n\n");
        for (self.document.modules) |module| {
            try self.print("<a id=\"module-{s}\"></a>\n\n### {s}\n\n", .{ try anchor(self.a, module.name), module.name });
            try self.prose(module.doc);
            if (module.declarations.len == 0) continue;
            try self.text("| Declaration | Summary | Markers |\n| --- | --- | --- |\n");
            for (module.declarations) |declaration| {
                try self.text("| ");
                try self.appendLocated(declaration, module.name);
                try self.print(" | {s} | ", .{try cell(self.a, collect.firstSentence(declaration.doc))});
                try self.markers(declaration);
                try self.text(" |\n");
            }
            try self.text("\n");
        }
    }
    fn renderDeclaration(self: *Writer, item: types.Declaration) !void {
        try self.print("<a id=\"decl-{s}\"></a>\n\n## {s}\n\n```selka\n{s}\n```\n\n", .{ try anchor(self.a, item.name), item.name, item.signature });
        try self.prose(item.doc);
        if (item.details.fields.len != 0) try self.fields(item.details.fields);
        for (item.details.cases) |case| {
            try self.print("Case `{s}`.\n\n", .{case.name});
            if (case.fields.len != 0) try self.fields(case.fields);
        }
        if (item.details.contracts.len != 0) {
            try self.text(if (std.mem.eql(u8, item.kind, "type")) "Invariants: " else "Contracts: ");
            for (item.details.contracts, 0..) |clause, i| {
                if (i != 0) try self.text("; ");
                try self.text(try code(self.a, clause));
            }
            try self.text(".\n\n");
        }
        if (item.details.function) |function| try self.renderFunction(function);
        if (item.decisions.len != 0) {
            try self.text("Decisions: ");
            try self.decisionLinks(item.decisions);
            try self.text(".\n\n");
        }
    }
    fn fields(self: *Writer, list: []const types.Field) !void {
        try self.text("| Field | Type | Default |\n| --- | --- | --- |\n");
        for (list) |field| {
            try self.print("| `{s}` | `{s}` | ", .{ field.name, try cell(self.a, field.type) });
            if (field.default) |value| try self.text(try code(self.a, try cell(self.a, value)));
            try self.text(" |\n");
        }
        try self.text("\n");
    }
    fn renderFunction(self: *Writer, function: types.Function) !void {
        try self.text("Facts:\n\n");
        if (function.writes.len != 0) {
            try self.text("- Writes: ");
            for (function.writes, 0..) |parameter, i| {
                if (i != 0) try self.text(", ");
                try self.print("`{s}`", .{parameter});
            }
            try self.text(".\n");
        }
        if (function.authority.len != 0) {
            try self.text("- Authority: ");
            for (function.authority, 0..) |parameter, i| {
                if (i != 0) try self.text(", ");
                try self.print("`{s}: {s}`", .{ parameter.name, parameter.type });
            }
            try self.text(".\n");
        }
        if (function.tests.len != 0) {
            try self.text("- Tested directly by: ");
            try self.names(function.tests);
            try self.text(".\n");
        }
        if (function.hole) try self.text("- Hole: the whole body is the `todo[T]()` obligation.\n");
        if (function.waiver) |reason| {
            try self.text("- Example waived: ");
            try self.prose(reason);
        }
        try self.text("\n");
    }
    fn markers(self: *Writer, item: types.Declaration) !void {
        const function = item.details.function orelse return;
        var first = true;
        if (function.writes.len != 0) {
            try self.text("`mut`");
            first = false;
        }
        for (function.authority) |parameter| {
            if (!first) try self.text(", ");
            try self.print("`{s}`", .{parameter.type});
            first = false;
        }
        if (function.fails) |failure| {
            if (!first) try self.text(", ");
            try self.print("`fails {s}`", .{try cell(self.a, failure)});
        }
    }
    fn history(self: *Writer) !void {
        if (self.document.releases.history.len == 0) return;
        try self.text("<a id=\"releases\"></a>\n\n## Releases\n\n");
        for (self.document.releases.history) |release| {
            try self.print("### {s} ({d} decisions)\n\n", .{ release.name, release.decisions });
            for (self.document.releases.decisions) |item| {
                if (item.pending or !std.mem.eql(u8, releaseName(item), release.name)) continue;
                try self.print("- [{s}]({s}): ", .{ decisionTitle(item), try self.decisionPath(item.path) });
                try self.linked(try facts.folded(self.a, collect.firstSentence(decisionWhy(item))));
                try self.text("\n");
            }
            try self.text("\n");
        }
    }
    fn decisionLinks(self: *Writer, refs: []const usize) !void {
        for (refs, 0..) |ref, i| {
            if (i != 0) try self.text(", ");
            const item = self.document.releases.decisions[ref];
            try self.print("[{s}]({s}) ({s})", .{ try cell(self.a, decisionTitle(item)), try self.decisionPath(item.path), if (item.pending) "unreleased" else releaseName(item) });
        }
    }
    fn names(self: *Writer, list: []const []const u8) !void {
        for (list, 0..) |item, i| {
            if (i != 0) try self.text(", ");
            try self.appendName(item);
        }
    }
    fn declarationNames(self: *Writer, list: []const []const u8) !void {
        for (list, 0..) |item, i| {
            if (i != 0) try self.text(", ");
            try self.appendLocatedByName(item);
        }
    }
    fn appendName(self: *Writer, value: []const u8) !void {
        if (self.locate(value)) |module| {
            return self.print("[`{s}`]({s}#decl-{s})", .{
                value,
                try self.destination(try paths.referencePath(self.a, self.document.releases.overview_path, module)),
                try anchor(self.a, value),
            });
        }
        try self.print("`{s}`", .{value});
    }
    fn appendLocated(self: *Writer, item: types.Declaration, module: []const u8) !void {
        const target = try paths.referencePath(self.a, self.document.releases.overview_path, module);
        try self.print("[`{s}`]({s}#decl-{s})", .{ item.name, try self.destination(target), try anchor(self.a, item.name) });
    }
    fn appendLocatedByName(self: *Writer, name: []const u8) !void {
        if (self.locate(name)) |module| {
            return self.print("[`{s}`]({s}#decl-{s})", .{
                name,
                try self.destination(try paths.referencePath(self.a, self.document.releases.overview_path, module)),
                try anchor(self.a, name),
            });
        }
        try self.print("`{s}`", .{name});
    }
    fn inlineModules(self: *Writer, list: []const []const u8) !void {
        for (list, 0..) |item, i| {
            if (i != 0) try self.text(", ");
            try self.text("[");
            try self.text(try cell(self.a, item));
            try self.text("](");
            try self.text(try self.destination(try paths.referencePath(self.a, self.document.releases.overview_path, item)));
            try self.text(")");
        }
    }
    fn moduleLinks(self: *Writer, label: []const u8, list: []const []const u8) !void {
        if (list.len == 0) return;
        try self.print("{s}: ", .{label});
        try self.inlineModules(list);
        try self.text(".\n\n");
    }
    /// The module that declares `name`, or null when nothing in the project does.
    fn locate(self: *Writer, name: []const u8) ?[]const u8 {
        for (self.document.modules) |module| for (module.declarations) |declaration| {
            if (std.mem.eql(u8, declaration.name, name)) return module.name;
        };
        return null;
    }
    fn linked(self: *Writer, value: []const u8) !void {
        var cursor: usize = 0;
        while (openingTick(value, cursor)) |start| {
            const width = tickWidth(value, start);
            const end = closingTicks(value, start + width, width) orelse break;
            try self.text(value[cursor..start]);
            const span = value[start + width .. end];
            const already_linked = start != 0 and value[start - 1] == '[' and std.mem.startsWith(u8, value[end + width ..], "](");
            if (decision.qualifiedName(span) and !already_linked) try self.appendName(span) else try self.text(value[start .. end + width]);
            cursor = end + width;
        }
        try self.text(value[cursor..]);
    }
    fn destination(self: *Writer, target: []const u8) ![]const u8 {
        const parent = std.fs.path.dirname(self.base) orelse ".";
        return linkDestination(self.a, try paths.relative(self.a, parent, target));
    }
    fn decisionPath(self: *Writer, path: []const u8) ![]const u8 {
        const parent = std.fs.path.dirname(self.base) orelse ".";
        return linkDestination(self.a, try paths.relative(self.a, parent, path));
    }
    fn prose(self: *Writer, raw: []const u8) !void {
        const value = try dedent(self.a, raw);
        if (value.len == 0) return;
        var lines = std.mem.splitScalar(u8, value, '\n');
        var fence: ?Fence = null;
        var example = false;
        const example_ticks = try delimiter(self.a, value, 3);
        while (lines.next()) |line| {
            const trimmed = std.mem.trimStart(u8, line, " \t");
            if (example and trimmed.len == 0) {
                try self.print("{s}\n", .{example_ticks});
                example = false;
            }
            if (fence == null and !example and std.mem.startsWith(u8, trimmed, ">>> ")) {
                try self.print("{s}text\n", .{example_ticks});
                example = true;
            }
            if (!example and fenceLine(&fence, trimmed)) {
                try self.text(line);
            } else if (fence != null or example) try self.text(line) else try self.linked(line);
            try self.text("\n");
        }
        if (example) try self.print("{s}\n", .{example_ticks});
        try self.text("\n");
    }
    fn extraProse(self: *Writer, body: []const u8) !void {
        var lines = std.mem.splitScalar(u8, body, '\n');
        _ = lines.next();
        var out: std.ArrayList(u8) = .empty;
        var skip = false;
        var fence: ?Fence = null;
        while (lines.next()) |line| {
            const trimmed = std.mem.trim(u8, line, " \t\r");
            if (fenceLine(&fence, trimmed)) skip = false;
            if (fence == null and metadataLine(trimmed)) {
                skip = std.mem.startsWith(u8, trimmed, "Why:");
                continue;
            }
            if (trimmed.len == 0) skip = false;
            if (!skip) try out.print(self.a, "{s}\n", .{line});
        }
        try self.prose(out.items);
    }
};

fn metadataLine(line: []const u8) bool {
    for ([_][]const u8{ "Changes:", "Date:", "Why:", "Rejected:" }) |prefix| if (std.mem.startsWith(u8, line, prefix)) return true;
    return false;
}
fn releaseName(item: decision.Decision) []const u8 {
    return std.fs.path.basename(std.fs.path.dirname(item.path) orelse "");
}
fn anchor(a: std.mem.Allocator, name: []const u8) ![]const u8 {
    const result = try a.dupe(u8, name);
    for (result) |*byte| if (byte.* == '.' or byte.* == ':') {
        byte.* = '-';
    };
    return result;
}
fn cell(a: std.mem.Allocator, value: []const u8) ![]const u8 {
    return std.mem.replaceOwned(u8, a, value, "|", "\\|");
}
fn delimiter(a: std.mem.Allocator, value: []const u8, minimum: usize) ![]const u8 {
    var width = minimum;
    var cursor: usize = 0;
    while (std.mem.indexOfScalarPos(u8, value, cursor, '`')) |start| {
        const run = tickWidth(value, start);
        width = @max(width, run + 1);
        cursor = start + run;
    }
    const result = try a.alloc(u8, width);
    @memset(result, '`');
    return result;
}
fn code(a: std.mem.Allocator, value: []const u8) ![]const u8 {
    const ticks = try delimiter(a, value, 1);
    const padding = if (std.mem.startsWith(u8, value, "`") or std.mem.endsWith(u8, value, "`")) " " else "";
    return std.fmt.allocPrint(a, "{s}{s}{s}{s}{s}", .{ ticks, padding, value, padding, ticks });
}
fn dedent(a: std.mem.Allocator, raw: []const u8) ![]const u8 {
    var lines = std.mem.splitScalar(u8, raw, '\n');
    const first = std.mem.trimEnd(u8, std.mem.trimStart(u8, lines.next() orelse "", " \t"), "\r");
    var indent: usize = std.math.maxInt(usize);
    while (lines.next()) |line| {
        const trimmed = std.mem.trimStart(u8, line, " \t");
        if (std.mem.trim(u8, trimmed, "\r").len != 0) indent = @min(indent, line.len - trimmed.len);
    }
    if (indent == std.math.maxInt(usize)) indent = 0;
    var out: std.ArrayList(u8) = .empty;
    try out.appendSlice(a, first);
    lines.reset();
    _ = lines.next();
    while (lines.next()) |line| {
        try out.append(a, '\n');
        try out.appendSlice(a, std.mem.trimEnd(u8, line[@min(indent, line.len)..], "\r"));
    }
    return std.mem.trim(u8, out.items, "\n");
}

fn openingTick(value: []const u8, start: usize) ?usize {
    var cursor = start;
    while (std.mem.indexOfScalarPos(u8, value, cursor, '`')) |at| {
        var before = at;
        while (before != 0 and value[before - 1] == '\\') before -= 1;
        if ((at - before) % 2 == 0) return at;
        cursor = at + 1;
    }
    return null;
}
fn tickWidth(value: []const u8, start: usize) usize {
    var end = start;
    while (end < value.len and value[end] == '`') end += 1;
    return end - start;
}
fn closingTicks(value: []const u8, start: usize, width: usize) ?usize {
    var cursor = start;
    while (std.mem.indexOfScalarPos(u8, value, cursor, '`')) |at| {
        const found = tickWidth(value, at);
        if (found == width) return at;
        cursor = at + found;
    }
    return null;
}

const Fence = struct { marker: u8, width: usize };
fn fenceLine(state: *?Fence, line: []const u8) bool {
    if (line.len < 3 or (line[0] != '`' and line[0] != '~')) return false;
    var width: usize = 0;
    while (width < line.len and line[width] == line[0]) width += 1;
    if (width < 3) return false;
    if (state.*) |open| {
        const matches = line[0] == open.marker and width >= open.width;
        if (matches and std.mem.trim(u8, line[width..], " \t\r").len == 0) state.* = null;
    } else state.* = .{ .marker = line[0], .width = width };
    return true;
}
fn linkDestination(a: std.mem.Allocator, path: []const u8) ![]const u8 {
    var result: std.ArrayList(u8) = .empty;
    for (path) |byte| {
        const punctuation = byte == '/' or byte == '.' or byte == '-' or byte == '_';
        if (std.ascii.isAlphanumeric(byte) or punctuation) try result.append(a, byte) else try result.print(a, "%{X:0>2}", .{byte});
    }
    return result.items;
}
fn decisionTitle(item: decision.Decision) []const u8 {
    if (item.metadata.title.len != 0) return item.metadata.title;
    var lines = std.mem.splitScalar(u8, item.body, '\n');
    while (lines.next()) |line| {
        const trimmed = std.mem.trim(u8, line, " \t\r");
        if (trimmed.len == 0) continue;
        if (std.mem.startsWith(u8, trimmed, "# ")) return trimmed[2..];
        break;
    }
    return item.identity;
}
fn decisionWhy(item: decision.Decision) []const u8 {
    if (item.metadata.why.len != 0) return item.metadata.why;
    var lines = std.mem.splitScalar(u8, item.body, '\n');
    while (lines.next()) |line| {
        const trimmed = std.mem.trim(u8, line, " \t\r");
        if (trimmed.len == 0 or trimmed[0] == '#' or metadataLine(trimmed)) continue;
        return trimmed;
    }
    return "No reason recorded.";
}
