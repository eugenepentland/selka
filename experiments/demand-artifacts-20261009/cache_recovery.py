#!/usr/bin/env python3
"""Exercise CLI recovery with surviving headers and missing raw/final/LLVM data."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import struct
import subprocess


MAGIC = b'mylang-stage-v1\n'
HEADER = len(MAGIC) + 64


def main_body(payload):
    """Read only the published Function prefix, never guess from file size."""
    if len(payload) < 12 or payload[:12] != struct.pack('<Q', 4) + b'main':
        return None
    params = struct.unpack_from('<Q', payload, 12)[0]
    instructions = 20 + 4 * params + 4 + 1 + 8 + 8
    if instructions + 8 > len(payload):
        return None
    return struct.unpack_from('<Q', payload, instructions)[0]


def llvm_artifact(payload):
    if len(payload) < 8:
        return False
    length = struct.unpack_from('<Q', payload)[0]
    if length > len(payload) - 8:
        return False
    text = payload[8:8 + length]
    return text.startswith(b'; generated by mylang-core\nsource_filename = ') and b'define ' in text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--compiler', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    root = args.output.resolve()
    root.mkdir(parents=True, exist_ok=False)
    source = root / 'main.my'
    source.write_text('func main() -> int:\n    return 42\n')
    cache = root / 'cache'
    executable = root / 'program'
    env = dict(os.environ, MYLANG_CORE_RUNTIME_CACHE=str(root / 'native'))
    rows = []

    def build(label):
        command = [str(args.compiler.resolve()), 'build', str(source), '-o', str(executable),
                   '--cache-dir', str(cache), '--optimize-debug', '--report']
        run = subprocess.run(command, cwd=root, env=env, capture_output=True)
        (root / f'{label}.stderr').write_bytes(run.stderr)
        assert run.returncode == 0, run.stderr.decode()
        record = next(json.loads(line) for line in run.stderr.decode().splitlines()
                      if line.startswith('{"version":"cache-report-v1"'))
        execution = subprocess.run([executable], capture_output=True)
        assert (execution.returncode, execution.stdout, execution.stderr) == (42, b'', b'')
        result = {'phase': label, 'cache': record, 'sha256': hashlib.sha256(executable.read_bytes()).hexdigest()}
        rows.append(result)
        return result

    original = build('setup')
    removed = []
    headers = []
    for path in (cache / 'stages-v1').glob('*.stage'):
        data = path.read_bytes()
        assert data.startswith(MAGIC)
        payload = data[HEADER:]
        instructions = main_body(payload)
        if instructions == 0:
            headers.append(path.name)
        elif instructions is not None or llvm_artifact(payload):
            removed.append(path.name)
            path.unlink()
    assert headers and len(removed) >= 3, (headers, removed)
    shutil.rmtree(cache / 'replay-v1')
    retained = build('native-reuse-without-llvm')
    assert retained['cache']['stages']['lowering']['fallbacks'] == 0
    assert retained['cache']['compiled'] == 0
    assert retained['sha256'] == original['sha256']
    shutil.rmtree(cache / 'replay-v1')
    shutil.rmtree(root / 'native' / 'units-v1')
    repaired = build('repair')
    assert repaired['cache']['stages']['lowering']['fallbacks'] >= 1
    assert repaired['sha256'] == original['sha256']
    assert all((cache / 'stages-v1' / name).is_file() for name in removed)
    shutil.rmtree(cache / 'replay-v1')
    warm = build('warm-after-repair')
    assert warm['cache']['stages']['lowering']['fallbacks'] == 0
    assert warm['cache']['compiled'] == 0
    assert warm['sha256'] == original['sha256']
    report = {'headers_preserved': headers, 'artifacts_removed_and_repaired': removed, 'records': rows}
    (root / 'results.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps({'headers_preserved': len(headers), 'artifacts_repaired': len(removed),
                      'fallbacks': [row['cache']['stages']['lowering']['fallbacks'] for row in rows],
                      'binary_identity_and_execution': 'passed'}), flush=True)


if __name__ == '__main__':
    main()
